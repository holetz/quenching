# the surface model — what every subcommand reads
# --------------------------------------------------------------------------- #
def command_invocation(relpath: str) -> str:
    """`specs/develop.md` -> `/specs:develop` — one `:` per path segment. The path IS
    the identity, so this is the whole naming rule; nothing derives a second name to
    compare it against."""
    return "/" + ":".join(relpath[:-3].split("/"))


def discover_commands(commands_dir: str) -> list[dict]:
    """Every `<commands_dir>/**/*.md`, sorted by invocation — one row per entry point.

    Every `.md` under the tree is a command, including one that should not be there:
    `commands/**` is the only tree Claude Code registers, so a stray file IS a
    registered entry point and must be reported as one, never filtered out here."""
    if not os.path.isdir(commands_dir):
        return []
    out = []
    for dirpath, _dirnames, filenames in os.walk(commands_dir):
        for fn in sorted(filenames):
            if not fn.endswith(".md"):
                continue
            path = os.path.join(dirpath, fn)
            relpath = rel(path, commands_dir)
            text = read_text(path) or ""
            body = body_after_frontmatter(text)
            hooks, hooks_parsed = parse_frontmatter_hooks(text)
            out.append({
                "command": command_invocation(relpath),
                "path": path,
                "relpath": relpath,
                "frontmatter": parse_frontmatter(text),
                "anomalies": frontmatter_anomalies(text),
                "hooks": hooks,
                "hooksParsed": hooks_parsed,
                "body": body,
                "bodyLines": len(body.splitlines()),
            })
    return sorted(out, key=lambda c: c["command"])


def discover_references(references_dir: str) -> list[dict]:
    """Every `<references_dir>/**/*.md` — the shared procedure a command body cites by
    absolute path instead of restating. These are NOT entry points and carry no
    invocation: they are prose the prose checks read, nothing more."""
    if not os.path.isdir(references_dir):
        return []
    out = []
    for dirpath, _dirnames, filenames in os.walk(references_dir):
        for fn in sorted(filenames):
            if not fn.endswith(".md"):
                continue
            path = os.path.join(dirpath, fn)
            text = read_text(path) or ""
            out.append({
                "path": path,
                "relpath": rel(path, references_dir),
                "body": body_after_frontmatter(text),
            })
    return sorted(out, key=lambda r: r["relpath"])


def load_surface(root: str) -> dict:
    return {
        "root": root,
        "commandsDir": os.path.join(root, COMMANDS_DIR),
        "commands": discover_commands(os.path.join(root, COMMANDS_DIR)),
    }


# --------------------------------------------------------------------------- #
# registration — each subcommand section below declares its own arguments and
# handler, so adding one never edits a table at the far end of the file
# --------------------------------------------------------------------------- #
SUBCOMMANDS: dict = {}   # name -> argument registrar
DISPATCH: dict = {}      # name -> handler(args, root) -> exit code


def register(name: str, add_args, handler) -> None:
    SUBCOMMANDS[name] = add_args
    DISPATCH[name] = handler


def finding(code: str, severity: str, message: str, **extra) -> dict:
    f = {"code": code, "severity": severity, "message": message}
    f.update(extra)
    return f


def exit_for(findings: list[dict]) -> int:
    """Errors are findings the exit code reports; warnings are reported and do not
    fail the run — the same split `specs.py doctor` and `validate` already use, so a
    conductor can gate on an exit code without a severity table of its own."""
    return 1 if any(f["severity"] == "error" for f in findings) else 0


def report_findings(args, header: str, payload: dict, findings: list[dict],
                    label_key: str = "skill") -> int:
    errors = sum(1 for f in findings if f["severity"] == "error")
    if args.json:
        print(json.dumps({"ok": errors == 0, **payload, "findings": findings},
                         indent=2, ensure_ascii=False))
    else:
        print(f"{header} ({errors} error(s), {len(findings) - errors} warning(s))")
        for f in findings:
            print(f"  [{f['severity']:<5}] {f.get(label_key, '-')}: {f['message']}  ({f['code']})")
        if not findings:
            print("  OK — no findings.")
    return exit_for(findings)


# --------------------------------------------------------------------------- #
# lint — the per-skill conformance checks
#
# Every check here is decidable FROM THE FILE. The doctrine's remaining tests —
# the no-op test, sediment, sprawl, positive prescription — stay a human read in
# `quenching-skill-align-and-update` Stage 2, because each needs a claim about
# behaviour that no parser can make. Adding a heuristic for one of them would move
# the plugin's anti-fabrication boundary, not the tool's coverage.
# --------------------------------------------------------------------------- #
def _split_sentences(text: str) -> list[str]:
    return [s for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s]


def _quoted_phrases(text: str) -> list[str]:
    return [m.group(1).strip() for m in QUOTED_RE.finditer(text) if m.group(1).strip()]


def _split_tools(spec: str) -> list[str]:
    """Split `Read, Bash(git add:*, git commit:*), Edit` on top-level commas only — a
    scoped grant may carry commas inside its parentheses."""
    out, depth, cur = [], 0, ""
    for ch in spec:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth = max(0, depth - 1)
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    out.append(cur.strip())
    return [t for t in out if t]


def _numbered_steps(body: str) -> list[str]:
    """The workflow's numbered steps: `### N. Title` headings, and top-level `N. …`
    list items once a `**Steps**` / `## Steps` / `## Workflow` marker has opened the
    workflow. Numbered prose lists elsewhere in the body are NOT steps — counting them
    would report a criterion missing from a list that never promised one."""
    steps, in_workflow = [], False
    for line in body.splitlines():
        if STEP_HEADING_RE.match(line):
            steps.append(line.strip())
            in_workflow = False
        elif WORKFLOW_MARKER_RE.match(line):
            in_workflow = True
        elif in_workflow and STEP_ITEM_RE.match(line):
            steps.append(line.strip())
        elif in_workflow and HEADING_RE.match(line):
            in_workflow = False
    return steps


def _step_criteria(body: str) -> tuple[int, int]:
    """(steps, steps carrying a `**Done when:**` criterion). A criterion belongs to the
    step it follows, so the body is walked once and each marker credited to the step
    most recently opened."""
    steps = _numbered_steps(body)
    if not steps:
        return 0, 0
    opened = set(steps)
    covered, current = set(), None
    for line in body.splitlines():
        stripped = line.strip()
        if stripped in opened:
            current = stripped
        elif current and DONE_WHEN_RE.search(line):
            covered.add(current)
    return len(steps), len(covered)


def lint_command(cmd: dict, base: str) -> list[dict]:
    fm, body = cmd["frontmatter"], cmd["body"]
    where = {"command": cmd["command"], "path": rel(cmd["path"], base)}
    if not fm:
        return [finding("sk-no-frontmatter", "error",
                        "the command file has no YAML frontmatter — Claude Code cannot load it",
                        **where)]
    out: list[dict] = []

    # BEFORE any content check, so a parse failure is never presented as a content
    # gap. A `description` truncated at a `#` used to surface as `sk-no-description`,
    # which names a missing part rather than the truncation that removed it.
    for a in cmd.get("anomalies", []):
        out.append(finding("sk-frontmatter-unparsed", "warn",
                           f"`{a['key']}`: {a['detail']}", kind=a["kind"], key=a["key"], **where))

    # `name` is not checked: the command's path IS its name, so there is no second
    # spelling that could disagree with it. `sk-no-name` and `sk-name-mismatch` are
    # deleted with the pair rather than reinterpreted.
    description = str(fm.get("description", "")).strip()
    if not description:
        out.append(finding("sk-no-description", "error",
                           "no `description` — the command can never be selected", **where))
        return out

    # one file, one description — `when_to_use` went with the skill half
    always_on = len(description)
    if always_on > CAP_METADATA:
        out.append(finding("sk-metadata-cap", "error",
                           f"description is {always_on} characters, over the "
                           f"{CAP_METADATA} cap — Claude Code truncates the tail, which is where "
                           "the `Not for:` boundary lives",
                           characters=always_on, cap=CAP_METADATA, **where))
    if len(description) > CAP_DESCRIPTION_PORTABLE:
        out.append(finding("sk-description-portable", "warn",
                           f"description is {len(description)} characters, over the "
                           f"{CAP_DESCRIPTION_PORTABLE} limit of the Agent Skills standard — the "
                           "command is not portable outside Claude Code",
                           characters=len(description), cap=CAP_DESCRIPTION_PORTABLE, **where))

    triggers = _quoted_phrases(description)
    if not triggers:
        out.append(finding("sk-trigger-position", "warn",
                           "the description quotes no trigger phrase — no user wording routes to "
                           "this command", **where))
    elif not _quoted_phrases(" ".join(_split_sentences(description)[:TRIGGER_SENTENCE_MAX])):
        out.append(finding("sk-trigger-position", "warn",
                           f"the first trigger phrase appears after sentence "
                           f"{TRIGGER_SENTENCE_MAX} — a truncated description loses it", **where))
    if BOUNDARY_MARKER not in description:
        out.append(finding("sk-no-boundary", "warn",
                           f"the description states no `{BOUNDARY_MARKER}` boundary — the routing "
                           "story is missing from the only text always in context", **where))

    if cmd["bodyLines"] > CAP_BODY_LINES:
        out.append(finding("sk-body-length", "error",
                           f"body is {cmd['bodyLines']} lines, over the {CAP_BODY_LINES} cap — "
                           "push shared procedure into a bundled reference and cite it by "
                           "absolute path",
                           lines=cmd["bodyLines"], cap=CAP_BODY_LINES, **where))

    steps, covered = _step_criteria(body)
    if steps and covered < steps:
        out.append(finding("sk-step-criterion", "warn",
                           f"{steps - covered} of {steps} numbered steps carry no "
                           f"`{DONE_WHEN_MARKER}` criterion — a step with no observable end state "
                           "can be claimed done early", steps=steps, covered=covered, **where))

    for bare in (t for t in _split_tools(str(fm.get("allowed-tools", ""))) if t in UNSCOPED_TOOLS):
        out.append(finding("sk-unscoped-bash", "warn",
                           f"`{bare}` is granted unscoped — scope it to the commands the workflow "
                           "runs, or state the reason in the body", tool=bare, **where))

    out.extend(_lint_invocation(fm, where))
    out.extend(_lint_frontmatter_hooks(cmd, where))
    out.extend(_lint_profile(fm, where))
    return out


def _lint_profile(fm: dict, where: dict) -> list[dict]:
    """The execution profile's mechanically decidable slice. `context: fork` runs the
    command in a forked context that CANNOT present a mid-flow question, so a fork beside
    an `AskUserQuestion` grant is incoherent by construction — the one profile combination
    that is an error rather than a judgment. Unparseable `context`/`effort` values are
    warned: Claude Code reads them as unset, so the command silently runs without the
    profile its author thought it had."""
    out: list[dict] = []
    context = str(fm.get("context", "")).strip().lower()
    if context and context != "fork":
        out.append(finding("sk-profile-value", "warn",
                           f"`context: {fm['context']}` is not a value Claude Code reads — "
                           "the only supported value is `fork`", **where))
    effort = str(fm.get("effort", "")).strip().lower()
    if effort and effort not in EFFORT_VALUES:
        out.append(finding("sk-profile-value", "warn",
                           f"`effort: {fm['effort']}` is not one of "
                           f"{'/'.join(EFFORT_VALUES)} — Claude Code reads it as unset",
                           **where))
    if context == "fork":
        tools = _split_tools(str(fm.get("allowed-tools", "")))
        if any(t == "AskUserQuestion" or t.startswith("AskUserQuestion(") for t in tools):
            out.append(finding("sk-fork-gate", "error",
                               "`context: fork` beside an `AskUserQuestion` grant — a forked "
                               "context cannot present a mid-flow question, so one of the two "
                               "is a lie", **where))
    return out


def _lint_invocation(fm: dict, where: dict) -> list[dict]:
    """Both keys are optional and default invocation is the norm — a collapsed command
    is typable at `/` AND reachable by name, which is what lets a conductor invoke a
    stage. The incoherence worth an error is the combination that leaves NO caller:
    the menu off and the model blocked."""
    out, values = [], {}
    for key in ("user-invocable", "disable-model-invocation"):
        if key not in fm:
            continue
        raw = str(fm[key]).strip().lower()
        if raw in ("true", "false"):
            values[key] = raw == "true"
        else:
            out.append(finding("sk-invocation-value", "warn",
                               f"`{key}: {fm[key]}` is not a boolean — Claude Code reads an "
                               "unparsable value as unset", **where))
    if values.get("user-invocable") is False and values.get("disable-model-invocation") is True:
        out.append(finding("sk-unreachable", "error",
                           "`user-invocable: false` with `disable-model-invocation: true` leaves "
                           "no way to invoke the command — neither the menu nor the model",
                           **where))

    return out


def _lint_frontmatter_hooks(cmd: dict, where: dict) -> list[dict]:
    """The scope ladder's narrowest rung. A frontmatter hook fires only while this command
    runs, which is why it is the default rung — but "narrow" is about SCOPE, not about cost:
    an unmatched matcher here still taxes every tool call the command makes, so the same two
    ladder codes apply, from the same implementation `settings.json` uses."""
    out: list[dict] = []
    if not cmd.get("hooksParsed", True):
        out.append(finding("sk-hook-unparseable", "warn",
                           "the frontmatter `hooks:` block does not match the mold's shape, so "
                           "the ladder checks could not read it — it is NOT reported as clean",
                           **where,
                           remedy="rewrite it in the shape of "
                                  "assets/templates/automation/hook.md shape 1 (/skill:hook:new)"))
    out.extend(hook_ladder_findings(cmd.get("hooks") or {},
                                    where_in=f"{where['path']} frontmatter", where=where))
    return out


def plugin_prefix(root: str) -> str | None:
    """The registry prefix this surface's commands carry, from `<root>/.claude-plugin/
    plugin.json`. `None` says the surface is a target repo's own `.claude/` — where a
    command file IS in `.claude/commands/`, the bare form is the one that resolves, and
    the citation check has nothing to say."""
    text = read_text(os.path.join(root, PLUGIN_MANIFEST))
    if text is None:
        return None
    try:
        name = json.loads(text).get("name")
    except (ValueError, AttributeError):
        return None
    return name.strip() if isinstance(name, str) and name.strip() else None


def bare_citations(body: str, invocations: set[str]) -> list[str]:
    """The bare `/front:verb` citations in `body` that name a command of THIS surface, in
    order of appearance and without repeats.

    `body` is the text after the frontmatter, so a citation inside `description:` cannot
    reach here — the boundary is the parse, never a pattern that has to be kept in step
    with one."""
    seen: list[str] = []
    for m in CITATION_RE.finditer(body):
        cite = "/" + m.group(1)
        if cite in invocations and cite not in seen:
            seen.append(cite)
    return seen


def lint_citations(prefix: str, body: str, invocations: set[str], where: dict) -> list[dict]:
    """One finding per file, never one per citation: a surface mid-sweep carries hundreds,
    and a report nobody can read is a report nobody acts on."""
    bare = bare_citations(body, invocations)
    if not bare:
        return []
    shown = ", ".join(f"`{c}`" for c in bare[:CITATION_SAMPLE])
    more = f" (+{len(bare) - CITATION_SAMPLE} more)" if len(bare) > CITATION_SAMPLE else ""
    return [finding("sk-bare-citation", "warn",
                    f"{plural(len(bare), 'bare command citation')} in the body — {shown}{more}. "
                    f"These commands come from the `{prefix}` plugin, so the form that resolves "
                    f"is `{prefix}:<front>:<verb>` for the Skill tool and "
                    f"`/{prefix}:<front>:<verb>` for a human; the bare form resolves only where "
                    "the command file lives in the target repo's own .claude/commands/",
                    citations=bare, **where)]


def resolve_lint_targets(path_arg: str | None, root: str) -> tuple[str, list[dict], list[dict]]:
    """(base, commands, references). Accepts a single command file, a commands/ directory,
    or a surface root — so `lint commands`, `lint .claude`, and `lint commands/docs/add.md`
    all mean what they read like.

    The references ride along only when the base IS a surface root: linting one file, or a
    bare `commands/` directory, is a scope the caller named and this never widens it."""
    if not path_arg:
        return (root, discover_commands(os.path.join(root, COMMANDS_DIR)),
                discover_references(os.path.join(root, REFERENCES_DIR)))
    target = os.path.abspath(path_arg)
    if os.path.isfile(target):
        parent = os.path.dirname(target)
        return parent, [c for c in discover_commands(parent)
                        if os.path.abspath(c["path"]) == target], []
    if os.path.isdir(os.path.join(target, COMMANDS_DIR)):
        return (target, discover_commands(os.path.join(target, COMMANDS_DIR)),
                discover_references(os.path.join(target, REFERENCES_DIR)))
    return target, discover_commands(target), []


def cmd_lint(args, root: str) -> int:
    base, commands, references = resolve_lint_targets(args.path, root)
    if not commands:
        return report_findings(args, f"skills lint — {base}", {"root": base, "commandCount": 0},
                               [finding("sk-no-commands", "error",
                                        f"no command file found under {base}",
                                        command=SURFACE_MISSING)])
    findings: list[dict] = []
    for cmd in commands:
        findings.extend(lint_command(cmd, base))

    prefix = plugin_prefix(root)
    if prefix:
        # What counts as a command of this surface is a property of the SURFACE, never of
        # the scope asked for — deriving it from `commands` would make `lint <one file>`
        # blind to every citation naming a sibling.
        invocations = {c["command"] for c in
                       (commands if base == root
                        else discover_commands(os.path.join(root, COMMANDS_DIR)))}
        for cmd in commands:
            findings.extend(lint_citations(prefix, cmd["body"], invocations,
                                           {"command": cmd["command"],
                                            "path": rel(cmd["path"], base)}))
        for ref in references:
            findings.extend(lint_citations(prefix, ref["body"], invocations,
                                           {"command": SURFACE_MISSING,
                                            "path": rel(ref["path"], base)}))

    header = f"skills lint — {base} ({plural(len(commands), 'command')}"
    header += f", {plural(len(references), 'reference')})" if references else ")"
    return report_findings(args, header,
                           {"root": base, "commandCount": len(commands),
                            "referenceCount": len(references)}, findings)


register("lint", lambda sp: sp.add_argument(
    "path", nargs="?",
    help="a command file, a commands/ directory, or a surface root"), cmd_lint)


# --------------------------------------------------------------------------- #
# doctor — the surface's shape
#
# `lint` judges one command against the doctrine; `doctor` judges the surface as a
# whole, which is where the front's convergence condition actually lives. Every
# finding carries a `remedy` the sweep applies rather than invents, the same
# contract `specs.py doctor` already gives the specs/ front.
#
# WHAT REPLACED THE BIJECTION. This used to check that every skill had exactly one
# mirrored wrapper and vice versa. With one file per entry point there is no second
# half that can be missing, duplicated, dangling, or misnamed, so `sk-orphan-skill`,
# `sk-dangling-wrapper`, `sk-duplicate-wrapper`, `sk-wrapper-no-target` and
# `sk-path-mismatch` are deleted rather than reinterpreted. The invariant that took
# their place is narrower and total: every command carries a non-empty `description`,
# no two resolve to the same `/` path, and every segment is kebab-case.
#
# The bijection did catch a real class of error — a skill minted without a wrapper —
# and nothing replaces it, because after the collapse that state cannot exist.
# --------------------------------------------------------------------------- #
def _doctor_findings(surface: dict) -> list[dict]:
    """Doctor's checks as a pure function, so `selftest` can assert on them without
    parsing printed output or re-implementing the rules it is meant to be proving."""
    commands = surface["commands"]
    findings: list[dict] = []

    seen_lower: dict[str, str] = {}
    for c in commands:
        where = {"command": c["command"], "path": c["relpath"]}

        # a stray file under commands/ IS a registered entry point with no way to be
        # selected — the phantom-command failure mode, caught by a check that existed
        if not str(c["frontmatter"].get("description", "")).strip():
            findings.append(finding("sk-no-description", "error",
                                    f"{c['command']} has no `description` — it registers as a "
                                    "command that can never be selected; if it is not an entry "
                                    f"point it does not belong under {COMMANDS_DIR}/", **where,
                                    remedy="add a description, or move the file out of "
                                           f"{COMMANDS_DIR}/ (shared procedure belongs beside the "
                                           "payload, never beside a command)"))

        for segment in c["relpath"][:-3].split("/"):
            if not KEBAB_RE.match(segment):
                findings.append(finding("sk-non-canonical-name", "error",
                                        f"`{segment}` in {c['command']} is not kebab-case",
                                        **where,
                                        remedy="rename the path segment to kebab-case (gate a "
                                               "code-coupled rename on its own)"))

        clash = seen_lower.setdefault(c["command"].lower(), c["command"])
        if clash != c["command"]:
            findings.append(finding("sk-name-collision", "error",
                                    f"{c['command']} collides with {clash} on a case-insensitive "
                                    "filesystem", **where,
                                    remedy="rename one of the two commands"))

    findings.extend(_wider_findings(surface["root"]))
    return findings


def _wider_findings(root: str) -> list[dict]:
    """REPORT-ONLY inventory of the surfaces beside commands/: subagent definitions
    (`<root>/agents/*.md`) and the hooks wired in `<root>/settings*.json`. The sweep never
    renames or rewrites anything here — each finding names the mint that owns the fix
    (/skill:agent:new, /skill:hook:new), so the confirmed plan's write set stays exactly
    the command surface's."""
    findings: list[dict] = []

    for fn, fm in agent_definitions(root):
        if not str(fm.get("description", "")).strip():
            findings.append(finding(
                "sk-agent-no-description", "error",
                f"agents/{fn} has no `description` — the agent can never be delegated to",
                command=f"agents/{fn}", path=f"agents/{fn}",
                remedy="add a description stating what it does and when to invoke it "
                       "(/skill:agent:new)"))

    for settings_name in ("settings.json", "settings.local.json"):
        text = read_text(os.path.join(root, settings_name))
        if text is None:
            continue
        try:
            hooks = json.loads(text).get("hooks", {})
        except (json.JSONDecodeError, AttributeError):
            findings.append(finding(
                "sk-hook-unparseable", "error",
                f"{settings_name} is not valid JSON — every hook wired in it is dead",
                command=settings_name, path=settings_name,
                remedy="repair the JSON (`python3 -m json.tool` names the position)"))
            continue
        if not isinstance(hooks, dict):
            continue
        findings.extend(hook_ladder_findings(
            hooks, where_in=settings_name,
            where={"command": settings_name, "path": settings_name}))
    return findings


def hook_ladder_findings(hooks: dict, where_in: str, where: dict) -> list[dict]:
    """The scope- and handler-ladder checks over a `hooks` object.

    Written once and run over BOTH rungs — the `settings.json` wiring and a command's
    frontmatter block — because the economics are identical: an unmatched tool-event
    hook taxes every tool call, and an inference handler charges a model call per
    firing, wherever the wiring happens to be declared."""
    out: list[dict] = []
    if not isinstance(hooks, dict):
        return out
    for event in TOOL_EVENTS:
        for entry in hooks.get(event) or []:
            if not isinstance(entry, dict):
                continue
            at = {**where, "event": event}
            if str(entry.get("matcher", "")).strip() in ("", "*"):
                out.append(finding(
                    "sk-hook-unmatched", "warn",
                    f"a {event} hook in {where_in} has no matcher — it fires on "
                    "every tool call, and every iteration in the repo pays it",
                    **at,
                    remedy="add a matcher, or state where it is wired why nothing "
                           "narrower suffices (/skill:hook:new owns the scope ladder)"))
            for h in entry.get("hooks") or []:
                if isinstance(h, dict) and str(h.get("type", "")).strip() in LLM_HANDLERS:
                    out.append(finding(
                        "sk-hook-llm-frequent", "warn",
                        f"a `{h.get('type')}` handler on {event} in {where_in} "
                        "runs an inference per matched tool call",
                        **at,
                        remedy="decide the deterministic path with a command handler "
                               "and keep the inference for the judgment tail "
                               "(/skill:hook:new owns the handler ladder)"))
    return out


