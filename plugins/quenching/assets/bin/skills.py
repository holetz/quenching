#!/usr/bin/env python3
"""skills.py — self-contained deterministic trail for the `.claude/` front.

Payload of the `quenching` plugin, third sibling of `assets/bin/specs.py` and
`assets/hooks/okf-validate.py` and built in the same mold: stdlib-only, ZERO
dependencies (its own minimal frontmatter parser — no PyYAML), one script installed
alone into a target repo.

WHY A THIRD TOOL
----------------
`docs/` has `okf-validate.py`; `specs/` has `specs.py`; the `.claude/` front had a
sentence. Its convergence condition — the registry's GENERATED zone matching
`commands/` exactly — was hand-generated by an LLM and hand-diffed by the same LLM,
and every conformance rule the front declares (the description cap, the trigger
position, the body length) was checked by reading. This script is what the front
branches on instead, so the skills ramify on DATA (an exit code, a `--json` field),
never on prose they infer.

Each front's align installs its OWN tool: folding these checks into `specs.py` or
`okf-validate.py` would make one front's align responsible for another front's
verifier — the exact coupling the three-front split exists to prevent.

THE SURFACE
-----------
A **surface root** is the directory holding an automation surface's `commands/` tree.
Two shapes are conformant and both resolve here:

    <target>/.claude/          # a target repo's local surface
      commands/<front>/[<object>/]<verb>.md

    plugins/<plugin-name>/     # a packaged plugin's surface (this repo's own shape)
      commands/<front>/[<object>/]<verb>.md

ONE FILE PER ENTRY POINT. Claude Code merged custom commands into skills, so a command
file carries its own description AND its own body; the `skills/<name>/SKILL.md` half it
used to be paired with is gone, and with it the bijection this tool once checked. A
command's path IS its invocation and its identity: `commands/specs/develop.md` is
`/specs:develop`, one `:` per path segment. There is nothing left to mirror.

`commands/**` is the ONLY tree Claude Code registers, which is why nothing else may
live there: a `references/` folder beside a command file would surface every reference
as a phantom entry. Such a file carries no `description`, so `sk-no-description`
already catches it — the layout rule needs no check of its own.

OUTPUT CONTRACT (uniform across every subcommand)
-------------------------------------------------
`--json` on every subcommand, and STRICT exit codes so the skill ramifies on data:
  0  ok
  1  findings (a check found something; a path did not resolve)
  2  refusal  (the tool declines to act — never merely "findings were found")

Findings carry a stable `sk-*` code, exactly as `docs/` reports OKF codes and
`specs/` reports `sp-*`, so the sweep, its conductor, and any status view name the
same defect the same way. ERRORS set the exit code; WARNINGS are reported and do
not — the same split `specs.py doctor` and `validate` already use.

SUBCOMMANDS
  lint [path]     per-command conformance: the two description caps, trigger position,
                  the `Not for:` boundary, body length, a `**Done when:**` criterion
                  per numbered step, unscoped `Bash`, invocation-control coherence, and
                  the execution profile's decidable slice (`sk-fork-gate`,
                  `sk-profile-value`).
                  Plus, on a surface carrying `.claude-plugin/plugin.json`, the citation
                  form (`sk-bare-citation`): a plugin's commands are namespaced, so a
                  bare `/front:verb` in prose resolves nowhere. Read from the body
                  ALONE, which is what keeps a `description:` out of it.
                  `path` accepts a command file, a commands/ directory, or a surface
                  root; it defaults to the resolved surface. A surface root also brings
                  in `assets/references/**` — prose the same session reads.
  doctor          the surface's shape: every command carries a non-empty `description`,
                  no two resolve to the same `/` path, and every path segment is
                  kebab-case. That invariant is what replaced the bijection — with one
                  file per entry point there is no second half to be missing.
                  Every finding carries a `remedy` the sweep applies.
                  Plus the REPORT-ONLY wider surface: `<root>/agents/*.md` and the hooks
                  wired in `<root>/settings*.json` (`sk-agent-no-description`,
                  `sk-hook-unmatched`, `sk-hook-llm-frequent`, `sk-hook-unparseable`) —
                  routed to their mints, never migrated by the sweep.
  registry reindex [--registry PATH]
                  regenerate the registry's GENERATED zone from the surface's own
                  command frontmatter, preserving every line of curated prose
                  outside the markers. Exits 1 when the repo carries no registry
                  doc or no zone markers — a table is never placed at a guessed
                  anchor inside prose a human wrote.
  budget [--ceiling N]
                  what the surface costs before anything fires: per command and
                  summed, sorted by cost, against the ceiling. Reports; never
                  refuses.
  read PATH [--sections "A,B"] [--rules-only]
                  N sections of any markdown file in ONE call, frontmatter stripped.
                  Without `--sections`, prints the file's heading index — what exists
                  to ask for, so discovering it never costs the file. A section runs
                  from its heading to the next heading of the SAME level or shallower,
                  so sub-headings travel with their parent; fenced code is never read
                  as a heading. A named section that does not exist is a refusal (2)
                  that names it, never an empty answer. `--rules-only` returns
                  the `<!-- rules -->` half of each section — and, where no marker is
                  present, the whole section plus a note saying so. Never silence.
  selftest        builds a throwaway surface in a temp dir and asserts doctor's
                  findings on it — chiefly that a file parked under commands/ which
                  is NOT an entry point registers as one and fires
                  `sk-no-description`. The layout rule's only evidence, since the
                  repo carries no test framework. Plus the section-reader's canonical
                  case list, proved here and against the same list by `specs.py`.

SURFACE RESOLUTION
  --root PATH, else $SKILLS_ROOT, else walking up from cwd: the first directory
  holding `.claude/commands/` (that `.claude` is the root) or `commands/` (that
  directory is the root). Falls back to `<cwd>/.claude`.

INTERPRETER
  Invoked as `python3 skills.py` or `py skills.py`; on a machine where both resolve to
  a stub, the caller falls back to the real interpreter path and says so in its report
  — the same resolution the `specs/` skills already carry for `specs.py`.
"""
