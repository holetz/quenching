# --------------------------------------------------------------------------- #
# drift — the installed copies against the plugin that ships them
#
# Each of the three tools is COPIED into a target's `.claude/hooks/` by its own align,
# and that offer is the only moment a version is ever compared. A repo that installed
# once and never aligned again keeps whatever it got, indefinitely, and nothing says
# so. This subcommand is what notices — without an align, and without writing.
#
# It MUST run from the plugin's own copy. An installed copy's `VERSION` is the stale
# number under test, so answering from it would report "all current" in exactly the
# case this exists to catch. An unresolvable plugin root is a refusal (exit 2), never
# a guess.
# --------------------------------------------------------------------------- #
PLUGIN_VERSION_FILE = "VERSION"

# The three tools an align installs, each with the path it ships at and the align that
# owns its copy. Nothing else under `.claude/hooks/` is this subcommand's business —
# a target's own scripts live there too, and auditing them would be a different claim.
#
# `wired` marks the ONE tool that is a hook. `okf-validate.py` does nothing unless a
# `hooks` block invokes it, so installed-and-uninvoked is a state it can sit in for
# months — this repo did. `specs.py` and `skills.py` are CLIs a command body calls, so
# their absence from settings.json is normal and asking about it would manufacture two
# false findings on every conformant repo.
INSTALLED_TOOLS = (
    {"tool": "okf-validate.py", "ships": "assets/hooks/okf-validate.py",
     "align": "/docs:align", "wired": True},
    {"tool": "specs.py", "ships": "assets/bin/specs.py",
     "align": "/specs:align", "wired": False},
    {"tool": "skills.py", "ships": "assets/bin/skills.py",
     "align": "/skill:align", "wired": False},
)

# Each tool declares `VERSION = "x.y.z"` at module level, in lockstep with the plugin's
# VERSION file. Reading the constant — rather than running the script for `--version` —
# keeps this a READ: `drift` is called from probes, and a probe that executes whatever
# sits in a target's `.claude/hooks/` is a different and much larger claim than one that
# reads three lines. A copy too old to declare one reads `unreadable`, which carries the
# same call to action as `behind`.
VERSION_CONSTANT_RE = re.compile(r'^VERSION\s*=\s*["\']([^"\']+)["\']', re.M)


def read_tool_version(path: str) -> str | None:
    text = read_text(path)
    if text is None:
        return None
    m = VERSION_CONSTANT_RE.search(text)
    return m.group(1).strip() if m else None


def _version_key(v: str) -> tuple | None:
    """`4.2.0` -> (4, 2, 0). Anything not purely numeric-dotted returns None, and an
    unorderable pair is reported as `unreadable` rather than ordered on a guess."""
    parts = v.split(".")
    if not all(p.isdigit() for p in parts):
        return None
    return tuple(int(p) for p in parts)


def compare_versions(installed: str | None, shipped: str) -> str:
    """`current` · `behind` · `ahead` · `unreadable`, for a copy that IS on disk —
    `absent` is the caller's, because "no file" and "a file I could not read" are
    different facts and only one of them is a repo that thinks it is protected.

    Both directions are reported because both are silent. Resolution is plugin-first
    (specs-front.md §Resolving the tool) while every align deliberately leaves a NEWER
    installed copy alone — so an `ahead` copy is code that is never executed and never
    repaired, and both halves of that are correct behaviour saying nothing."""
    if installed is None:
        return "unreadable"
    a, b = _version_key(installed), _version_key(shipped)
    if a is None or b is None:
        return "unreadable"
    return "current" if a == b else ("behind" if a < b else "ahead")


def settings_hook_commands(root: str) -> list[str]:
    """Every `command` string wired under a `hooks` event, across both settings files.

    Reuses the pair `doctor` already reads (`settings.json` + `settings.local.json`) so
    a per-developer override counts as wiring. Unparseable JSON yields nothing here and
    is `doctor`'s finding to report — two tools naming the same broken file twice is
    noise, and `drift` would only be guessing at what the file meant."""
    out: list[str] = []
    for settings_name in ("settings.json", "settings.local.json"):
        text = read_text(os.path.join(root, settings_name))
        if text is None:
            continue
        try:
            hooks = json.loads(text).get("hooks", {})
        except (json.JSONDecodeError, AttributeError):
            continue
        if not isinstance(hooks, dict):
            continue
        for entries in hooks.values():
            for entry in entries if isinstance(entries, list) else []:
                if not isinstance(entry, dict):
                    continue
                for h in entry.get("hooks") or []:
                    if isinstance(h, dict) and isinstance(h.get("command"), str):
                        out.append(h["command"])
    return out


def drift_rows(root: str, plugin_root: str, shipped: str) -> list[dict]:
    """One row per tool. `executes` is the copy a command actually runs: the documented
    fallback tries the plugin path first, so it is the plugin's whenever this ran at all
    — which is exactly what makes an `ahead` row worth printing."""
    rows = []
    wired_commands = settings_hook_commands(root)
    for spec in INSTALLED_TOOLS:
        installed_path = os.path.join(root, HOOKS_DIR, spec["tool"])
        present = os.path.isfile(installed_path)
        installed = read_tool_version(installed_path) if present else None
        # the SHIPPED tool's own constant, not the plugin's VERSION file: it is what an
        # install would put on disk, so it is what an installed copy must be compared
        # against. The two agreeing is the lockstep's business, checked elsewhere.
        tool_shipped = read_tool_version(os.path.join(plugin_root, spec["ships"])) or shipped
        rows.append({
            "tool": spec["tool"],
            "align": spec["align"],
            "installedPath": installed_path if present else None,
            "installed": installed,
            "shipped": tool_shipped,
            "status": "absent" if not present else compare_versions(installed, tool_shipped),
            "executes": "plugin",
            # None for the two CLIs: "we did not ask" is not "we found nothing"
            "wired": (any(spec["tool"] in c for c in wired_commands)
                      if spec["wired"] else None),
        })
    return rows


def drift_findings(rows: list[dict]) -> list[dict]:
    """One finding per row that is not `current`, each naming the align that fixes it.

    Severity follows what the state COSTS. `behind` is an error: a stale copy answers a
    different CLI contract, so anything running it by hand branches on a payload shape
    that no longer exists. `unwired` is an error: the script is inert, and the repo
    believes it is protected. `ahead` and `unreadable` are warnings — the plugin copy
    still runs, so nothing is currently wrong, only unmaintainable. `absent` is a
    warning for the HOOK alone, and no finding at all for the two CLIs (see below)."""
    out: list[dict] = []
    for r in rows:
        tool, align = r["tool"], r["align"]
        if r["status"] == "behind":
            out.append(finding(
                "sk-tool-behind", "error",
                f"{HOOKS_DIR}/{tool} is {r['installed']}, the plugin ships {r['shipped']} — "
                "commands resolve the plugin copy first, but a session without the plugin, "
                "a hook, or a human at a shell runs this one and gets its older CLI contract",
                tool=tool, installed=r["installed"], shipped=r["shipped"],
                remedy=f"{align} offers the overwrite"))
        elif r["status"] == "ahead":
            out.append(finding(
                "sk-tool-ahead", "warn",
                f"{HOOKS_DIR}/{tool} is {r['installed']}, ahead of the plugin's {r['shipped']} — "
                "resolution is plugin-first and every align leaves a newer copy alone, so this "
                "code is neither executed nor repaired",
                tool=tool, installed=r["installed"], shipped=r["shipped"],
                remedy="upgrade the plugin, then re-run " + align))
        elif r["status"] == "unreadable":
            out.append(finding(
                "sk-tool-unreadable", "warn",
                f"{HOOKS_DIR}/{tool} declares no `VERSION = \"…\"` — too old to carry one, or "
                "edited in place; either way no comparison can be made",
                tool=tool, remedy=f"{align} reinstalls it"))
        elif r["status"] == "absent" and r["wired"] is not None:
            # Only for the hook. A missing CLI costs nothing while the plugin is loaded —
            # resolution is plugin-first — and warning about it fires on every plugin-only
            # repo, including this one, which is how a probe's output gets ignored. A
            # missing HOOK is the same practical state as an unwired one: the bundle has
            # no enforcement at all. The row still reports `absent` either way.
            out.append(finding(
                "sk-tool-absent", "warn",
                f"no {HOOKS_DIR}/{tool} installed — nothing enforces the bundle between "
                "aligns, the same practical state as an installed copy nothing invokes",
                tool=tool, remedy=f"{align} installs and wires it"))
        if r["wired"] is False and r["status"] != "absent":
            out.append(finding(
                "sk-tool-unwired", "error",
                f"{HOOKS_DIR}/{tool} is installed but no `hooks` block in settings.json or "
                "settings.local.json invokes it — the script sits on disk and nothing fires it, "
                "so deleting it would change no behaviour",
                tool=tool, remedy=f"{align} merges the wiring into .claude/settings.json"))
    return out


def resolve_plugin_root(arg: str | None) -> str | None:
    """`--plugin-root` when given, else the plugin checkout this script runs from.

    A plugin holds `VERSION` beside `assets/`, so walking up from `assets/bin/skills.py`
    finds it in two hops. A copy installed at `.claude/hooks/skills.py` has no such
    parent — which is the case that must refuse rather than answer."""
    if arg:
        candidates = [arg]
    else:
        candidates, d = [], os.path.dirname(os.path.abspath(__file__))
        for _ in range(4):
            candidates.append(d)
            parent = os.path.dirname(d)
            if parent == d:
                break
            d = parent
    for c in candidates:
        if (os.path.isfile(os.path.join(c, PLUGIN_VERSION_FILE))
                and os.path.isdir(os.path.join(c, "assets"))):
            return os.path.abspath(c)
    return None


def _drift_refusal(args, given: str | None) -> int:
    """Exit 2 — the refusal branch of the 0 ok / 1 findings / 2 refusal contract. A
    caller that cannot tell "no drift" from "could not look" would report the silence
    this whole subcommand exists to break."""
    if given:
        message = (f"--plugin-root {given} holds no {PLUGIN_VERSION_FILE} beside an "
                   f"assets/ directory — it is not a plugin checkout")
    else:
        message = ("cannot resolve the plugin this script ships with — `drift` must run "
                   "from the plugin's own copy, because an installed copy would answer "
                   "from the same stale VERSION it is being asked about")
    remedy = ("run `python3 ${CLAUDE_PLUGIN_ROOT}/assets/bin/skills.py drift`, or pass "
              "--plugin-root <the plugin checkout>")
    if args.json:
        print(json.dumps({"ok": False, "refused": message, "remedy": remedy},
                         indent=2, ensure_ascii=False))
    else:
        print("skills drift — refused")
        print(f"  {message}")
        print(f"  remedy: {remedy}")
    return 2


def cmd_drift(args, root: str) -> int:
    given = getattr(args, "plugin_root", None)
    plugin_root = resolve_plugin_root(given)
    if plugin_root is None:
        return _drift_refusal(args, given)
    shipped = (read_text(os.path.join(plugin_root, PLUGIN_VERSION_FILE)) or "").strip()
    rows = drift_rows(root, plugin_root, shipped)
    findings = drift_findings(rows)
    payload = {"root": root, "pluginRoot": plugin_root, "shipped": shipped, "tools": rows}
    if args.json:
        print(json.dumps({"ok": not findings, **payload, "findings": findings},
                         indent=2, ensure_ascii=False))
        return exit_for(findings)
    print(f"skills drift — {root} against plugin {shipped} ({plugin_root})")
    for r in rows:
        wiring = "" if r["wired"] is None or r["status"] == "absent" else (
            "  wired" if r["wired"] else "  NOT wired — nothing invokes it")
        print(f"  {r['status']:<10} {r['tool']:<18} installed "
              f"{r['installed'] or '-':<8} shipped {r['shipped']:<8} "
              f"executes: {r['executes']}{wiring}")
    for f in findings:
        print(f"  [{f['severity']:<5}] {f['message']}  ({f['code']})")
        print(f"          remedy: {f['remedy']}")
    if not findings:
        print("  OK — every installed copy matches the plugin that ships it.")
    return exit_for(findings)


register("drift",
         lambda sp: sp.add_argument("--plugin-root",
                                    help="the plugin checkout holding VERSION beside assets/ "
                                         "(default: the one this script runs from)"),
         cmd_drift)


# --------------------------------------------------------------------------- #
# read — N sections of any markdown file, in ONE call
# --------------------------------------------------------------------------- #
# `specs.py section` reads a SPEC, whose fourteen headings are a validated contract.
# A reference or a standard is free markdown, so the two cannot share an
# implementation — but they must not disagree about what a section IS. Per
# `docs/standards/code/canonical-set-parsing.md`, what is shared is the RULE, proved by
# both tools against SECTION_CASES below.
FENCE_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})")
MD_HEADING_RE = re.compile(r"^ {0,3}(#{1,6})\s+(.+?)\s*#*\s*$")


def _strip_frontmatter(lines: list[str]) -> list[str]:
    """A leading `---` block is a header, never content. ~1,424 chars per OKF doc that
    a section reader has no reason to carry."""
    if not lines or lines[0].strip() != "---":
        return lines
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return lines[i + 1:]
    return lines


def markdown_sections(text: str) -> list[dict]:
    """Every heading of a markdown file, in order, each with the body it owns.

    Two rules, and both are the reason this is code rather than an `awk` in 26 command
    bodies:

    - **A section ends at the next heading of the same level or shallower.** So
      sub-headings travel with their parent, exactly as `## Impact` keeps its parsed
      `### Standards …` sub-heading in `specs.py`. Ending at the next heading of ANY
      level would orphan them.
    - **A fenced block is never read as a heading.** Several sections here open with
      ```` ```bash ```` blocks containing `## ` comments, and a line-matching reader
      slices the section in half at one — silently, returning a plausible answer.
    """
    lines = _strip_frontmatter(text.splitlines())
    heads: list[dict] = []
    fence: str | None = None
    for lineno, line in enumerate(lines):
        m = FENCE_RE.match(line)
        if m:
            mark = m.group(1)
            if fence is None:
                fence = mark[0] * len(mark)
            elif mark[0] == fence[0] and len(mark) >= len(fence):
                fence = None
            continue
        if fence is not None:
            continue
        h = MD_HEADING_RE.match(line)
        if h:
            heads.append({"level": len(h.group(1)), "heading": h.group(2).strip(),
                          "lineno": lineno})
    for i, h in enumerate(heads):
        end = len(lines)
        for nxt in heads[i + 1:]:
            if nxt["level"] <= h["level"]:
                end = nxt["lineno"]
                break
        h["body"] = "\n".join(lines[h["lineno"] + 1:end]).strip("\n")
    return heads


RULES_MARKER = "<!-- rules -->"
RATIONALE_MARKER = "<!-- rationale -->"


def split_rule_and_rationale(body: str) -> tuple[str, bool]:
    """The rule half of a section, and whether a marker actually said where it ends.

    **Marker, never heuristic.** A model deciding per read which sentences are binding and
    which are the story behind them is non-deterministic, and its failure is silent: a
    dropped binding sentence shows up nowhere. The marker is written once, by whoever wrote
    the rule, and the read is mechanical.

    **No marker → the whole section, and the caller is TOLD.** The degradation is to
    today's behaviour, never to emptiness. A convention applied in five files must not turn
    the other eighteen into silence.
    """
    if RULES_MARKER not in body:
        return body, False
    after = body.split(RULES_MARKER, 1)[1]
    return after.split(RATIONALE_MARKER, 1)[0].strip("\n"), True


def normalize_heading(name: str) -> str:
    """What a caller types against what the file carries. `§The commit`, `## The commit`
    and `the commit` are the same request — the citation form the bodies already use
    carries the `§`, and refusing over it would make the reader unusable from the very
    prose it exists to serve."""
    return " ".join(name.strip().lstrip("#§").strip().split()).casefold()


def select_sections(heads: list[dict], wanted: list[str]) -> tuple[list[dict], list[str]]:
    """The requested sections in the order they were ASKED FOR, plus the names that
    resolved to nothing. Duplicate headings resolve to the first — the same rule
    `parse_sections` applies in `specs.py`."""
    index: dict[str, dict] = {}
    for h in heads:
        index.setdefault(normalize_heading(h["heading"]), h)
    got, missing = [], []
    for name in wanted:
        h = index.get(normalize_heading(name))
        (got.append(h) if h else missing.append(name))
    return got, missing


SECTION_FIXTURE = '''---
type: standard
title: the section reader's fixture
---

# Top

Preamble under a level-1 heading.

## Alpha

Alpha body.

### Alpha sub

Sub body that belongs to Alpha.

## Beta

Beta opens with a fenced block whose lines look like headings:

```bash
## not a heading
### also not a heading
```

Beta continues after the fence.

## Gamma

~~~
## fenced by tildes
~~~

Gamma ends the file.
'''

# The canonical case list for the SECTION rule, duplicated verbatim in `specs.py`.
# EDIT BOTH, OR NEITHER — exactly as `CANONICAL_CASES` is duplicated across all three
# tools for the frontmatter rule. Neither script may import the other: each installs
# standalone into a target's `.claude/hooks/`, so the list travelling with each copy is
# what makes the rule provable where it actually runs.
#
# It covers only what BOTH tools answer the same way: level-2 sections. A spec's
# fourteen headings are all `##`, so that is the whole of `specs.py`'s contract, while
# `skills.py` also resolves `#` and `###` over free markdown and proves those separately.
SECTION_CASES = {
    "index": ["Alpha", "Beta", "Gamma"],
    "cases": [
        {"why": "sub-headings travel with their parent, and the section stops at the "
                "next heading of the same level",
         "ask": ["Alpha"],
         "contains": ["Alpha body.", "### Alpha sub", "Sub body that belongs to Alpha."],
         "excludes": ["Beta continues"]},
        {"why": "a fenced block containing `## ` never splits the section",
         "ask": ["Beta"],
         "contains": ["## not a heading", "Beta continues after the fence."],
         "excludes": ["Gamma ends"]},
        {"why": "tilde fences count too, and the last section runs to end of file",
         "ask": ["Gamma"],
         "contains": ["## fenced by tildes", "Gamma ends the file."],
         "excludes": []},
        {"why": "the citation form the bodies already use resolves: `§X` and `## X` "
                "are the same request, and N sections come back in the order asked",
         "ask": ["§Gamma", "## Alpha"],
         "contains": ["Gamma ends the file.", "Alpha body."],
         "excludes": [],
         "order": ["Gamma", "Alpha"]},
        {"why": "neither frontmatter nor the preamble above the first section ever "
                "leaks into a section that does not own it",
         "ask": ["Alpha", "Beta", "Gamma"],
         "contains": [],
         "excludes": ["type: standard", "Preamble under a level-1 heading."]},
        {"why": "a section that does not exist is a refusal that names it, never an "
                "empty answer",
         "ask": ["Delta"],
         "missing": ["Delta"]},
    ],
}


def section_case_findings(read_sections) -> list[dict]:
    """Run the canonical list against one tool's reader.

    `read_sections(fixture_text, wanted)` returns `(sections, missing)`, where each
    section is a mapping with `heading` and `body`. Both tools supply that adapter over
    their own implementation, so the list is the contract and neither is the reference.
    """
    out: list[dict] = []
    heads = [h["heading"] for h in read_sections(SECTION_FIXTURE, None)[0]
             if h.get("level", 2) == 2]
    if heads != SECTION_CASES["index"]:
        out.append(finding("sk-section-index", "error",
                           f"heading index is {heads}, expected "
                           f"{SECTION_CASES['index']}",
                           remedy="a fenced line was read as a heading, or a heading "
                                  "was missed"))
    for case in SECTION_CASES["cases"]:
        got, missing = read_sections(SECTION_FIXTURE, case["ask"])
        want_missing = case.get("missing", [])
        if missing != want_missing:
            out.append(finding("sk-section-missing", "error",
                               f"{case['ask']}: missing is {missing}, expected "
                               f"{want_missing} — {case['why']}",
                               remedy="an absent section must refuse, naming itself"))
            continue
        if want_missing:
            continue
        body = "\n".join(f"{'#' * s.get('level', 2)} {s['heading']}\n{s['body']}"
                         for s in got)
        for needle in case["contains"]:
            if needle not in body:
                out.append(finding("sk-section-body", "error",
                                   f"{case['ask']}: missing {needle!r} — {case['why']}",
                                   remedy="the section rule dropped content it owns"))
        for needle in case["excludes"]:
            if needle in body:
                out.append(finding("sk-section-body", "error",
                                   f"{case['ask']}: leaked {needle!r} — {case['why']}",
                                   remedy="the section rule captured content it does "
                                          "not own"))
        if "order" in case and [s["heading"] for s in got] != case["order"]:
            out.append(finding("sk-section-order", "error",
                               f"{case['ask']}: order is "
                               f"{[s['heading'] for s in got]}, expected "
                               f"{case['order']} — {case['why']}",
                               remedy="N sections come back in the order asked"))
    return out


def read_sections_adapter(text: str, wanted: list[str] | None) -> tuple[list[dict], list[str]]:
    """This tool's arm of the canonical list."""
    heads = markdown_sections(text)
    if wanted is None:
        return heads, []
    return select_sections(heads, wanted)


def cmd_read(args, root: str) -> int:
    path = pathlib.Path(args.path)
    if not path.is_file():
        payload = {"ok": False, "code": "sk-read-no-file", "path": str(path),
                   "message": f"{path} is not a file"}
        print(json.dumps(payload, indent=2, ensure_ascii=False) if args.json
              else f"error: {path} is not a file")
        return 2
    heads = markdown_sections(path.read_text(encoding="utf-8"))

    if not args.sections:
        index = [{"heading": h["heading"], "level": h["level"], "chars": len(h["body"])}
                 for h in heads]
        if args.json:
            print(json.dumps({"ok": True, "path": str(path), "index": index},
                             indent=2, ensure_ascii=False))
        else:
            print(f"{path} — {len(index)} sections")
            for h in index:
                print(f"  {'  ' * (h['level'] - 1)}{'#' * h['level']} {h['heading']}"
                      f"  ({h['chars']} chars)")
        return 0

    wanted = [s for s in (p.strip() for p in args.sections.split(",")) if s]
    got, missing = select_sections(heads, wanted)
    if missing:
        # A refusal, never an empty answer: a caller that asked for a rule and got
        # silence proceeds as though the rule did not exist.
        payload = {"ok": False, "code": "sk-read-no-section", "path": str(path),
                   "missing": missing,
                   "available": [h["heading"] for h in heads],
                   "message": f"{path} has no section named: {', '.join(missing)}"}
        print(json.dumps(payload, indent=2, ensure_ascii=False) if args.json
              else f"error: {path} has no section named: {', '.join(missing)}\n"
                   f"  available: {', '.join(h['heading'] for h in heads)}")
        return 2

    rows = []
    for h in got:
        body, marked = ((h["body"], True) if not args.rules_only
                        else split_rule_and_rationale(h["body"]))
        rows.append({"heading": h["heading"], "level": h["level"], "body": body,
                     **({"marked": marked} if args.rules_only else {})})

    if args.json:
        print(json.dumps({"ok": True, "path": str(path), "rulesOnly": args.rules_only,
                          "sections": rows}, indent=2, ensure_ascii=False))
    else:
        for r in rows:
            print(f"{'#' * r['level']} {r['heading']}\n\n{r['body']}\n")
        unmarked = [r["heading"] for r in rows if r.get("marked") is False]
        if unmarked:
            # Stated, never silent: the caller asked for the rule half and got the whole
            # section, and a reader that does not know which one it holds cannot tell a
            # compact rule from a section nobody has marked up yet.
            print(f"note: no {RULES_MARKER} marker in: {', '.join(unmarked)} — returned "
                  f"the whole section")
    return 0


