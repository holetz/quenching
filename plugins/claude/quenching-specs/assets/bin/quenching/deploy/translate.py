"""Target translation for `cq deploy`.

The plugin's command bodies are written for the plugin surface.  A deployed target has one
generic layer: skills under ``.agents/skills/``, the payload under ``.agents/quenching/`` and no
``CLAUDE.md``.  This module performs the deterministic, text-only pass that makes those bodies
resolve there.  It never decides what to deploy; `tree` does.
"""
from __future__ import annotations

import json
import re

from quenching.common.version import VERSION

PAYLOAD = ".agents/quenching"
CQ = PAYLOAD + "/bin/cq"
HEADER = f"<!-- generated by cq deploy {VERSION}; edit the source, not this file -->"
DROP_FRONTMATTER = {"model", "effort", "context", "hooks", "tools", "name"}
KEEP_FRONTMATTER = {"description", "argument-hint", "allowed-tools", "disable-model-invocation",
                    "user-invocable"}
AGENTS = ("git-steward", "orchestrator", "reviewer", "scout", "spec-architect", "spec-runner",
          "verifier")

CQ_INVOCATION = re.compile(
    r"(?<![\w./-])cq(?=\s+(?:--root|--version|--help|specs|knowledge|design|components|git|"
    r"ops|proof|toolchain|delivery|security|opensource|config|portal|session)\b)")
EXPLICIT_CQ = re.compile(
    r"python3\s+(?:\"?\.agents/quenching/)?(?:assets/bin|bin)/cq\"?")
PLUGIN_COMMAND = re.compile(r"/(quenching-[a-z]+):([A-Za-z0-9:-]+)")
BARE_COMMAND = re.compile(r"(?<![/\w-])(quenching-[a-z]+):([A-Za-z0-9:-]+)")
AGENT_ID = re.compile(r"\bquenching-specs:(" + "|".join(map(re.escape, AGENTS)) + r")\b")
# Both the source grant and its already-translated form: a target-local `cq deploy` reads the
# payload's own agent bodies, so the second translation must produce the first one's output.
CQ_GRANT = re.compile(r"Bash\(((?:cq|" + re.escape(CQ) + r")(?:\.cmd)?)(?: ([^:()]+))?:\*\)$")


def skill_name(relpath: str) -> str:
    """`specs/create.md` -> `quenching-specs-create`."""
    return "quenching-" + relpath[:-3].replace("/", "-")


def agent_name(name: str) -> str:
    return "quenching-" + name


def _flat_description(lines: list[str], start: int) -> tuple[str, int]:
    """Read a folded/literal YAML scalar beginning at `start`; return its text and next index."""
    pieces: list[str] = []
    index = start
    while index < len(lines) and (lines[index].startswith((" ", "\t")) or not lines[index].strip()):
        pieces.append(lines[index].strip())
        index += 1
    return " ".join(piece for piece in pieces if piece), index


def split_frontmatter(raw: str) -> tuple[dict[str, str], str]:
    if not raw.startswith("---\n"):
        return {}, raw
    end = raw.find("\n---\n", 4)
    if end < 0:
        return {}, raw
    fields: dict[str, str] = {}
    lines = raw[4:end].splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.strip() or line.lstrip().startswith("#"):
            index += 1
            continue
        key, sep, value = line.partition(":")
        if not sep:
            index += 1
            continue
        key, value = key.strip(), value.strip()
        if value in {">", ">-", "|", "|-"}:
            value, index = _flat_description(lines, index + 1)
        else:
            index += 1
        fields[key] = value
    return fields, raw[end + len("\n---\n"):]


def scalar_value(value: str) -> str:
    """A frontmatter scalar as text, accepting a target's already JSON-quoted form."""
    if len(value) >= 2 and value.startswith('"') and value.endswith('"'):
        try:
            parsed = json.loads(value)
        except ValueError:
            return value
        return parsed if isinstance(parsed, str) else value
    return value


def _module_id(match: re.Match) -> str:
    return "/quenching-" + match.group(2).replace(":", "-")


def _bare_id(match: re.Match) -> str:
    return "quenching-" + match.group(2).replace(":", "-")


def _agent_id(match: re.Match) -> str:
    return agent_name(match.group(1))


def transform_platform(text: str) -> str:
    """The one prose pass every deployed Markdown file receives."""
    text = AGENT_ID.sub(_agent_id, text)
    text = PLUGIN_COMMAND.sub(_module_id, text)
    text = BARE_COMMAND.sub(_bare_id, text)
    text = text.replace("${CLAUDE_PLUGIN_ROOT}/assets/", PAYLOAD + "/assets/")
    text = text.replace("${CLAUDE_PLUGIN_ROOT}", PAYLOAD)
    text = text.replace("${CLAUDE_PROJECT_DIR}", ".")
    text = text.replace(".claude/quenching.json", ".agents/quenching.json")
    text = text.replace(".claude/commands/", ".agents/skills/")
    text = text.replace("CLAUDE.md", "AGENTS.md")
    text = text.replace("Claude Code", "the host")
    text = text.replace("bare `cq`", f"the target-local `{CQ}`")
    text = text.replace("bare cq", f"the target-local `{CQ}`")
    text = EXPLICIT_CQ.sub(CQ, text)
    text = CQ_INVOCATION.sub(CQ, text)
    for marker in ("${CLAUDE_PLUGIN_ROOT}", "${CLAUDE_PROJECT_DIR}", "CLAUDE_PLUGIN_ROOT"):
        if marker in text:
            raise ValueError(f"untranslated platform marker: {marker}")
    return text


def transform_tools(value: str) -> str:
    """Keep the shipped grant, re-rooted at the target-local `cq` and its `cq.cmd` twin."""
    value = re.sub(r"Bash\(cq((?:\.cmd)?[^)]*):\*\)",
                   lambda m: f"Bash({CQ}{m.group(1)}:*)", value)
    def target_agent(item: str) -> str:
        name = item.strip().split(":")[-1]
        return name if name.startswith("quenching-") else agent_name(name)

    value = re.sub(r"Agent\(([^)]*)\)",
                   lambda m: "Agent(" + ", ".join(
                       target_agent(item) for item in m.group(1).split(",")
                       if item.strip()) + ")", value)
    return value


def _frontmatter(fields: list[tuple[str, str]]) -> str:
    return "---\n" + "".join(f"{key}: {value}\n" for key, value in fields) + "---\n\n"


def _body(value: str) -> str:
    """A body with deployment's own separator/header removed, so a second pass is stable."""
    value = value.lstrip("\n")
    if value.startswith(HEADER):
        value = value[len(HEADER):].lstrip("\n")
    return value


LAUNCHER_NOTE = ("**Launcher.** On POSIX the skill calls `cq`; on Windows it calls "
                 "`cq.cmd`, the sibling the deploy installs beside `bin/cq`.\n\n")


def _with_launcher_note(body: str) -> str:
    """Put the platform choice right under the skill's title, once, where every run reads it."""
    if LAUNCHER_NOTE in body:
        return body
    head, _, tail = body.partition("\n")
    if head.startswith("# "):
        return f"{head}\n\n{LAUNCHER_NOTE}{tail.lstrip(chr(10))}"
    return LAUNCHER_NOTE + body


def skill_document(raw: str, relpath: str) -> str:
    fields, body = split_frontmatter(raw)
    description = scalar_value(fields.get("description", ""))
    if not description:
        raise ValueError(f"command has no description: {relpath}")
    name = skill_name(relpath)
    out: list[tuple[str, str]] = [("name", name),
                                  ("description", json.dumps(transform_platform(description),
                                                             ensure_ascii=False))]
    for key in ("argument-hint", "allowed-tools", "disable-model-invocation", "user-invocable"):
        if key in fields:
            value = transform_tools(fields[key]) if key == "allowed-tools" else scalar_value(fields[key])
            out.append((key, json.dumps(transform_platform(value), ensure_ascii=False)
                        if key == "argument-hint" else transform_platform(value)))
    return (_frontmatter(out) + HEADER + "\n\n"
            + _with_launcher_note(transform_platform(_body(body))))


def command_document(raw: str) -> str:
    """A vendored command body the conductor reads from ``<payload>/commands``."""
    fields, body = split_frontmatter(raw)
    if not fields:
        return transform_platform(raw)
    out: list[tuple[str, str]] = []
    for key, value in fields.items():
        if key == "description":
            value = json.dumps(transform_platform(scalar_value(value)), ensure_ascii=False)
        elif key == "allowed-tools":
            value = transform_tools(value)
        elif key == "argument-hint":
            value = json.dumps(transform_platform(scalar_value(value)), ensure_ascii=False)
        out.append((key, value))
    return _frontmatter(out) + transform_platform(_body(body))


def reference_document(raw: str) -> str:
    return transform_platform(raw)


def _cq_patterns(names: list[str]) -> list[str]:
    """One `<target cq> <verbs> *` pattern per scoped `Bash(cq <verbs>:*)` grant, in order."""
    patterns: list[str] = []
    for name in names:
        match = CQ_GRANT.match(name)
        if not match:
            continue
        launcher = CQ + (".cmd" if match.group(1).endswith(".cmd") else "")
        patterns.append(f"{launcher} {match.group(2)} *" if match.group(2) else f"{launcher} *")
    return patterns


def opencode_permissions(tools: str | None) -> dict[str, str | dict[str, str]]:
    """A source `tools:` list as OpenCode permissions: deny-first, with the cq grants allowed.

    OpenCode applies the last matching rule, so the catch-all bash pattern comes first. The
    mapping mirrors the OpenCode distribution's agent writer; it lives here too because the
    deploy payload must translate without the repository's scripts/ tree.
    """
    if tools is None:
        return {}
    names = [item.strip() for item in re.split(r",\s*(?![^()]*\))", tools) if item.strip()]
    heads = {name.split("(", 1)[0] for name in names}
    granted: dict[str, str | dict[str, str]] = {}
    granted["edit"] = "allow" if heads & {"Edit", "Write", "NotebookEdit"} else "deny"
    granted["webfetch"] = "allow" if "WebFetch" in heads else "deny"
    if "Bash" in names:
        granted["bash"] = "allow"
    elif patterns := _cq_patterns(names):
        granted["bash"] = {"*": "ask", **dict.fromkeys(patterns, "allow")}
    else:
        granted["bash"] = "ask" if "Bash" in heads else "deny"
    granted["task"] = "allow" if heads & {"Agent", "Task"} else "deny"
    return granted


def opencode_agent_document(raw: str, name: str) -> str:
    """An OpenCode subagent: `mode: subagent`, deny-first permissions and the translated body."""
    fields, body = split_frontmatter(raw)
    description = scalar_value(fields.get("description", ""))
    if not description:
        raise ValueError(f"agent has no description: {name}")
    granted = opencode_permissions(fields.get("tools"))
    denies_task = granted.pop("task", "allow") == "deny"
    out = ["---", f"description: {json.dumps(transform_platform(description), ensure_ascii=False)}",
           "mode: subagent"]
    if granted:
        out.append("permission:")
        for key, value in granted.items():
            if isinstance(value, dict):
                out.append(f"  {key}:")
                out.extend(f'    "{pattern}": {mode}' for pattern, mode in value.items())
            else:
                out.append(f"  {key}: {value}")
    if denies_task:
        out.extend(["tools:", "  task: false"])
    out.append("---")
    preferences = []
    if fields.get("model"):
        preferences.append(f"Source model tier: `{scalar_value(fields['model'])}`.")
    if fields.get("effort"):
        preferences.append(f"Declared effort: `{scalar_value(fields['effort'])}`.")
    preamble = "\n\n".join(preferences) + "\n\n" if preferences else ""
    return "\n".join(out) + "\n\n" + HEADER + "\n\n" + preamble + transform_platform(_body(body))


def agent_document(raw: str, name: str) -> str:
    fields, body = split_frontmatter(raw)
    description = scalar_value(fields.get("description", ""))
    if not description:
        raise ValueError(f"agent has no description: {name}")
    out: list[tuple[str, str]] = [("name", agent_name(name)),
                                  ("description", json.dumps(transform_platform(description),
                                                             ensure_ascii=False))]
    if fields.get("tools"):
        out.append(("tools", transform_tools(fields["tools"])))
    for key in ("model", "effort"):
        if fields.get(key):
            out.append((key, fields[key]))
    return _frontmatter(out) + HEADER + "\n\n" + transform_platform(_body(body))
