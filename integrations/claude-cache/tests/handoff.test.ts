// /quenching-cache handoff's pure parts: the facts cq printed, the abbreviated conversation,
// the brief check against quenching's template, and the file `cq specs handoff write` stores.
import { expect, test } from 'claude-code/testing'
import type { SessionMessage } from 'claude-code'

import { REQUIRED_SECTIONS, assemble, briefPrompt, briefSystem, draftPath, factsSection, fenced, isValidBrief, lastRequest, parseFacts, renderTranscript, userText } from '../hooks/handoff'

const user = (text: string): SessionMessage => ({ role: 'user', text, toolUses: [] })
const asst = (text: string, toolUses: SessionMessage['toolUses'] = []): SessionMessage => ({ role: 'assistant', text, toolUses })
const tool = (tool: string, input: Record<string, unknown>, text?: string) => ({ tool_use_id: 'x', tool, input, text })

const FACTS = JSON.stringify({ ok: true, branch: 'plan/7-x', spec: 7, filesModified: ['a.ts'], commits: ['abc1234 Fix the bar'], lastUserMessage: 'ship it', transcript: '/t/c.jsonl' })

test('facts: what cq printed, and empty lists when it printed nothing usable', () => {
  expect(parseFacts(FACTS)).toEqual({ branch: 'plan/7-x', spec: 7, filesModified: ['a.ts'], commits: ['abc1234 Fix the bar'], lastUserMessage: 'ship it', transcript: '/t/c.jsonl' })
  expect(parseFacts(null)).toEqual({ branch: null, spec: null, filesModified: [], commits: [], lastUserMessage: null, transcript: undefined })
  expect(parseFacts('not json')).toEqual({ filesModified: [], commits: [] })
})

test('the last request: the facts\' when cq read it, else the session\'s own last real message', () => {
  const msgs = [user('first'), user('second'), user('<system-reminder>x</system-reminder>')]
  expect(lastRequest(parseFacts(FACTS), msgs)).toBe('ship it')
  expect(lastRequest(parseFacts(null), msgs)).toBe('second')
  expect(lastRequest(parseFacts(null), [])).toBe(null)
})

test('the facts section: exact, from code, never from a model', () => {
  const s = factsSection(parseFacts(FACTS), { tokens: 228_000, window: 1_000_000, model: 'claude-opus-5-5', bar: '🔴 cache expired' })
  expect(s).toContain('## Facts')
  expect(s).toContain('- **Branch:** plan/7-x')
  expect(s).toContain('- **Spec:** 7')
  expect(s).toContain('- **Chat size:** 228000 tokens of a 1000000 window')
  expect(s).toContain('### Files modified\n- a.ts')
  expect(s).toContain('### Commits\n- abc1234 Fix the bar')
  expect(factsSection(parseFacts(null), {})).toContain('- **Spec:** none')
})

test('Haiku reads the plugin\'s rules, then quenching\'s template without its generated header', () => {
  const sys = briefSystem('Rules.\n', '<!-- generated by x -->\n# Handoff template\n\n## Last Request\n')
  expect(sys).toBe('Rules.\n\n# Handoff template\n\n## Last Request')
  const p = briefPrompt([user('ship it')], parseFacts(FACTS), {})
  expect(p).toContain('## Last user message (verbatim)\nship it')
  expect(p).toContain('# Conversation\n### user')
})

test('brief check: the two sections cq specs handoff write requires, as headings', () => {
  expect(REQUIRED_SECTIONS).toEqual(['## Last Request', '## Next Actions'])
  expect(isValidBrief('## Handoff Confidence\nHigh')).toBe(false)
  expect(isValidBrief('## Last Request\nx\n\n## Next Actions\n1. y')).toBe(true)
  expect(isValidBrief('text mentioning ## Last Request and ## Next Actions inline')).toBe(false)
})

test('the stored file: Haiku\'s handoff plus the facts; without a usable one, a facts-only one that still passes', () => {
  const facts = parseFacts(FACTS)
  const good = assemble(facts, {}, [], '## Last Request\nship it\n\n## Next Actions\n1. Release.', undefined)
  expect(good.startsWith('## Last Request\nship it')).toBe(true)
  expect(good).toContain('\n\n## Facts\n')
  const bare = assemble(facts, {}, [], undefined, 'Haiku refused')
  expect(isValidBrief(bare)).toBe(true)
  expect(bare).toContain('Low: facts only — Haiku refused.')
  expect(bare).toContain('## Last Request\nship it\nStatus: Not answered')
})

test('harness rows are labelled, never taken for the user', () => {
  expect(userText(user('<command-name>/model</command-name>'))).toBe(undefined)
  expect(userText(user('[Image #1] [Image #2]'))).toBe(undefined)
  expect(userText(user('[Image #1] review this'))).toBe('[Image #1] review this')
  const t = renderTranscript([user('real ask'), user('<task-notification>done</task-notification>')])
  expect(t).toContain('### user\n```\nreal ask\n```')
  expect(t).toContain('### system signal (not the user)')
})

test('transcript limits: 120 newest messages, 2,000 chars each, tool input 300, no tool output', () => {
  const many = Array.from({ length: 130 }, (_, i) => user(`msg-${i}`))
  const t = renderTranscript(many)
  expect(t.includes('msg-9\n') || t.endsWith('msg-9')).toBe(false)
  expect(t).toContain('msg-129')
  expect(renderTranscript([user('x'.repeat(2_500))])).toContain(`${'x'.repeat(2_000)} [truncated]`)
  const w = renderTranscript([asst('', [tool('Bash', { command: 'y'.repeat(1_000) }, 'SECRET-OUTPUT')])])
  expect(w.includes('y'.repeat(300))).toBe(false)
  expect(w.includes('SECRET-OUTPUT')).toBe(false)
  expect(renderTranscript(Array.from({ length: 100 }, (_, i) => user(`${i}:${'z'.repeat(1_900)}`))).length).toBe(150_000)
})

test('a fence is longer than any backtick run inside it', () => {
  expect(fenced('a ```` b')).toBe('`````\na ```` b\n`````')
})

test('the draft lands under .quenching/handoff/, one file per handoff', () => {
  expect(draftPath(1_800_000_000_000, 'ab754061-473c')).toBe('.quenching/handoff/draft-1800000000000-ab754061.md')
})
