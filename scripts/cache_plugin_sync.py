"""Generate the `quenching-cache` plugin's copies of what quenching owns, or check them.

The plugin installs into no repository (it is a marketplace satellite), so it cannot read
`quenching/` at run time. Two files are therefore generated into it, and the gate refuses a stale
copy the way `deployed surface lockstep` refuses a stale install:

- `hooks/prices.ts` from `quenching/assets/bin/quenching/session/pricing.json`, the one price table
  `cq components session cost|cache --usd` also reads;
- `hooks/handoff-template.md` from `quenching/skills/quenching-handoff/references/template.md`, the
  section list both handoff doors write.

    python3 scripts/cache_plugin_sync.py --write   # regenerate
    python3 scripts/cache_plugin_sync.py --check   # exit 1 naming each stale copy
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "quenching" / "assets" / "bin"))

from quenching.session.pricing import TABLE, problems  # noqa: E402

PLUGIN = ROOT / "integrations" / "claude-cache" / "hooks"
TEMPLATE = ROOT / "quenching" / "skills" / "quenching-handoff" / "references" / "template.md"
HEAD = "generated by scripts/cache_plugin_sync.py from {src}; edit the source, then --write"


def prices_ts() -> str:
    data = json.loads(TABLE.read_text(encoding="utf-8"))
    rows = "\n".join(f"  '{key}': [{row['input']}, {row['cacheRead']}],"
                     for key, row in data["models"].items())
    long = ", ".join(f"'{k}': {{ above: {v['above']}, multiplier: {v['multiplier']} }}"
                     for k, v in data["longPrompt"].items())
    src = TABLE.relative_to(ROOT).as_posix()
    return (f"// {HEAD.format(src=src)}\n"
            "// USD per million tokens: [input, cache read], keyed by exact family-version.\n"
            f"export const PRICES_DATE = '{data['sourceDate']}'\n"
            "export const PRICES: Record<string, [input: number, read: number]> = {\n"
            f"{rows}\n}}\n"
            f"export const MULTIPLIERS = {{ write5m: {data['cacheWrite']['5m']}, "
            f"write1h: {data['cacheWrite']['1h']}, output: {data['output']}, fast: {data['fast']} }}\n"
            f"export const LONG_PROMPT: Record<string, {{ above: number; multiplier: number }}> = {{ {long} }}\n")


def template_md() -> str:
    src = TEMPLATE.relative_to(ROOT).as_posix()
    return f"<!-- {HEAD.format(src=src)} -->\n" + TEMPLATE.read_text(encoding="utf-8")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    bad = problems()
    if bad:
        print("pricing.json refused:\n  " + "\n  ".join(bad))
        return 1
    stale = []
    for path, text in ((PLUGIN / "prices.ts", prices_ts()), (PLUGIN / "handoff-template.md", template_md())):
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if args.write:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
        else:
            stale.append(path.relative_to(ROOT).as_posix())
    if stale:
        print("stale generated copies (run python3 scripts/cache_plugin_sync.py --write):\n  "
              + "\n  ".join(stale))
        return 1
    print("quenching-cache copies are current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
