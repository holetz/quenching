"""The path-scoped rule projection: one source under `.agents/rules/`, one generated copy per
client directory a declared client reads, and the deploy manifest owns the copies — never the
source. The source without `paths:` refuses, because an always-on instruction belongs in
`AGENTS.md`.
"""
from __future__ import annotations

import contextlib
import io
import json
import os
import pathlib
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

try:
    import _paths  # noqa: F401
except ModuleNotFoundError:
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    import _paths  # noqa: F401

from quenching.deploy import translate  # noqa: E402
from quenching.deploy import tree as deploy_tree  # noqa: E402
from quenching.deploy.cli import main as deploy_main  # noqa: E402

PLUGIN_ROOT = pathlib.Path(__file__).resolve().parent.parent

RULE = """---
paths:
  - "quenching/skills/**"
  - "quenching/references/**"
description: "A rule that loads only for the matched files."
---

# A rule

Do not do the thing.
"""


class Projection(unittest.TestCase):
    """A real deploy in a throwaway target, read as the two clients read it."""

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.target = pathlib.Path(tmp.name)
        self.git("init", "-q")
        self.xdg = pathlib.Path(tempfile.mkdtemp(dir=tmp.name, prefix="xdg-"))
        env = mock.patch.dict(os.environ, {"XDG_CONFIG_HOME": str(self.xdg), "OPENCODE_CONFIG": ""})
        env.start()
        self.addCleanup(env.stop)
        self.precompile = mock.patch("quenching.deploy.cli._precompile", return_value=None)
        self.precompile.start()
        self.addCleanup(self.precompile.stop)

    def git(self, *argv):
        return subprocess.run(["git", "-C", str(self.target), *argv], check=True,
                              capture_output=True, text=True).stdout

    def rule(self, name="guard", text=RULE):
        path = self.target / ".agents" / "rules" / f"{name}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def configure_projections(self, value):
        (self.target / ".agents").mkdir(exist_ok=True)
        (self.target / ".agents" / "quenching.json").write_text(
            json.dumps({"shared": {"projections": value}}, indent=2) + "\n", encoding="utf-8")

    def deploy(self, *argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(io.StringIO()):
            code = deploy_main(["--target", str(self.target), *argv, "--json"])
        return code, json.loads(out.getvalue() or "{}")

    def test_one_source_becomes_the_two_client_documents_and_the_source_is_not_owned(self):
        self.rule()
        self.configure_projections(["github"])
        code, payload = self.deploy("--modules", "specs", "--harness", "claude", "--write")
        self.assertEqual(0, code, payload)
        claude = (self.target / ".claude/rules/guard.md").read_text(encoding="utf-8")
        copilot = (self.target / ".github/instructions/guard.instructions.md").read_text(
            encoding="utf-8")
        self.assertTrue(claude.startswith('---\npaths:\n  - "quenching/skills/**"\n'
                                           '  - "quenching/references/**"\n'
                                           'description: "A rule that loads only for the matched '
                                           'files."\n---\n\n'))
        self.assertIn("<!-- generated by cq deploy", claude)
        self.assertIn("# A rule", claude)
        self.assertTrue(copilot.startswith(
            '---\napplyTo: "quenching/skills/**, quenching/references/**"\n'
            'description: "A rule that loads only for the matched files."\n---\n\n'))
        self.assertIn("<!-- generated by cq deploy", copilot)
        self.assertNotIn("paths:", copilot)
        files = json.loads((self.target / ".agents/.quenching-deploy.json").read_text())["files"]
        self.assertIn(".claude/rules/guard.md", files)
        self.assertIn(".github/instructions/guard.instructions.md", files)
        self.assertNotIn(".agents/rules/guard.md", files)

    def test_without_the_projection_key_only_the_claude_copy_is_written(self):
        self.rule()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertTrue((self.target / ".claude/rules/guard.md").is_file())
        self.assertFalse((self.target / ".github/instructions").exists())

    def test_without_the_claude_harness_the_copilot_copy_still_lands(self):
        self.rule()
        self.configure_projections(["github"])
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "opencode", "--write")[0])
        self.assertFalse((self.target / ".claude/rules").exists())
        self.assertTrue((self.target / ".github/instructions/guard.instructions.md").is_file())

    def test_a_rule_without_paths_refuses_before_anything_is_written(self):
        self.rule(text="---\ndescription: always on\n---\n\nBody.\n")
        code, payload = self.deploy("--modules", "specs", "--write")
        self.assertEqual((2, "ct-deploy-source"), (code, payload["code"]))
        self.assertIn("paths", payload["message"])
        self.assertFalse((self.target / ".agents/.quenching-deploy.json").exists())
        self.assertFalse((self.target / ".claude/rules").exists())

    def test_an_unknown_frontmatter_key_refuses(self):
        self.rule(text="---\npaths:\n  - \"src/**\"\nalwaysApply: true\n---\n\nBody.\n")
        code, payload = self.deploy("--modules", "specs", "--write")
        self.assertEqual((2, "ct-deploy-source"), (code, payload["code"]))
        self.assertIn("alwaysApply", payload["message"])

    def test_a_rule_name_that_is_not_a_flat_slug_refuses(self):
        self.rule(name="Guard Rule")
        code, payload = self.deploy("--modules", "specs", "--write")
        self.assertEqual((2, "ct-deploy-source"), (code, payload["code"]))
        self.assertIn("flat slug", payload["message"])

    def test_editing_a_projection_is_drift_and_a_write_refuses(self):
        self.rule()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        projection = self.target / ".claude/rules/guard.md"
        projection.write_text(projection.read_text(encoding="utf-8") + "\nedited\n",
                              encoding="utf-8")
        code, payload = self.deploy("--modules", "specs", "--check")
        self.assertEqual(1, code)
        self.assertIn({"path": ".claude/rules/guard.md", "change": "edited"}, payload["changes"])
        code, payload = self.deploy("--modules", "specs", "--write")
        self.assertEqual((2, "ct-deploy-edited"), (code, payload["code"]))
        self.assertIn(".claude/rules/guard.md", payload["paths"])

    def test_a_hand_written_projection_is_refused(self):
        self.rule()
        hand = self.target / ".claude/rules/guard.md"
        hand.parent.mkdir(parents=True)
        hand.write_text("---\npaths:\n  - \"src/**\"\n---\n\nMine.\n", encoding="utf-8")
        code, payload = self.deploy("--modules", "specs", "--harness", "claude", "--write")
        self.assertEqual((2, "ct-deploy-unowned"), (code, payload["code"]))
        self.assertIn(".claude/rules/guard.md", [item["path"] for item in payload["conflicts"]])

    def test_removing_the_source_removes_the_projection_on_the_next_write(self):
        source = self.rule()
        self.configure_projections(["github"])
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertTrue((self.target / ".claude/rules/guard.md").is_file())
        source.unlink()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertFalse((self.target / ".claude/rules").exists())
        self.assertFalse((self.target / ".github/instructions").exists())


class Translation(unittest.TestCase):
    def test_the_build_tree_carries_both_documents_and_the_copilot_one_only_with_the_key(self):
        with tempfile.TemporaryDirectory() as tmp:
            target = pathlib.Path(tmp)
            source = target / ".agents/rules/guard.md"
            source.parent.mkdir(parents=True)
            source.write_text(RULE, encoding="utf-8")
            plain = deploy_tree.build_tree(PLUGIN_ROOT, target, ["quenching-specs"], ["claude"])
            self.assertIn(".claude/rules/guard.md", plain["tree"])
            self.assertFalse([rel for rel in plain["tree"] if rel.startswith(".github/")])
            projected = deploy_tree.build_tree(PLUGIN_ROOT, target, ["quenching-specs"],
                                               ["claude"], projections=["github"])
            self.assertIn(".github/instructions/guard.instructions.md", projected["tree"])

    def test_a_quoted_glob_survives_both_documents(self):
        claude, copilot = translate.rule_documents(
            "---\npaths:\n  - \"src/**\"\n---\n\nBody.\n", "guard")
        self.assertIn('  - "src/**"', claude)
        self.assertIn('applyTo: "src/**"', copilot)

    def test_an_empty_paths_list_refuses(self):
        with self.assertRaises(ValueError):
            translate.rule_documents("---\npaths:\n---\n\nBody.\n", "guard")
