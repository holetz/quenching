"""The Copilot setup-steps projection: ONE generated workflow, opt-in by `shared.projections:
["github"]`, carrying the target's own Python, the deploy's `uvx` runtime and the declared
`shared.worktreeSetup` verbatim. The client reads the path and the job name; the deploy knows
neither a harness nor a client branch."""
from __future__ import annotations

import contextlib
import io
import json
import os
import pathlib
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

try:
    import _paths  # noqa: F401
except ModuleNotFoundError:
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    import _paths  # noqa: F401

from quenching.deploy import translate  # noqa: E402
from quenching.deploy import tree as deploy_tree  # noqa: E402
from quenching.deploy.cli import main as deploy_main  # noqa: E402

PLUGIN_ROOT = pathlib.Path(__file__).resolve().parent.parent
SETUP = ".github/workflows/copilot-setup-steps.yml"


class Projection(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.target = pathlib.Path(tmp.name)
        subprocess.run(["git", "-C", str(self.target), "init", "-q"], check=True,
                       capture_output=True)
        xdg = pathlib.Path(tempfile.mkdtemp(dir=tmp.name, prefix="xdg-"))
        env = mock.patch.dict(os.environ, {"XDG_CONFIG_HOME": str(xdg), "OPENCODE_CONFIG": ""})
        env.start()
        self.addCleanup(env.stop)
        precompile = mock.patch("quenching.deploy.cli._precompile", return_value=None)
        precompile.start()
        self.addCleanup(precompile.stop)

    def configure(self, projections=("github",), setup=None):
        document = {}
        shared = {}
        if projections is not None:
            shared["projections"] = list(projections)
        if setup is not None:
            shared["worktreeSetup"] = setup
        if shared:
            document["shared"] = shared
        path = self.target / ".agents/quenching.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(document), encoding="utf-8")

    def deploy(self, *argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(io.StringIO()):
            code = deploy_main(["--target", str(self.target), *argv, "--json"])
        return code, json.loads(out.getvalue() or "{}")

    def setup_file(self) -> pathlib.Path:
        return self.target / SETUP

    def test_the_workflow_is_one_job_with_the_target_declaration(self):
        (self.target / ".python-version").write_text("3.12\n", encoding="utf-8")
        self.configure(setup="uv sync --frozen")
        code, payload = self.deploy("--modules", "specs", "--harness", "claude", "--write")
        self.assertEqual(0, code, payload)
        text = self.setup_file().read_text(encoding="utf-8")
        self.assertTrue(text.startswith("# generated by cq deploy"))
        self.assertIn("name: Copilot Setup Steps", text)
        self.assertIn("  copilot-setup-steps:\n", text)
        self.assertIn("    runs-on: ubuntu-latest\n", text)
        self.assertIn("      contents: read\n", text)
        self.assertIn("      - uses: actions/checkout@v7\n", text)
        self.assertIn('          python-version-file: ".python-version"\n', text)
        self.assertIn('        run: "uv sync --frozen"\n', text)
        self.assertNotIn("setup-uv", text)
        self.assertIn("workflow_dispatch:", text)
        self.assertIn("      - .github/workflows/copilot-setup-steps.yml\n", text)
        files = json.loads((self.target / ".agents/.quenching-deploy.json").read_text())["files"]
        self.assertIn(SETUP, files)

    def test_the_plugin_floor_is_the_fallback_pin(self):
        self.configure()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        text = self.setup_file().read_text(encoding="utf-8")
        self.assertIn('          python-version: "3.11"\n', text)
        self.assertNotIn("worktreeSetup", text)

    def test_a_pyproject_with_requires_python_is_the_version_file(self):
        (self.target / "pyproject.toml").write_text(
            '[project]\nname = "x"\nrequires-python = ">=3.12"\n', encoding="utf-8")
        self.configure()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        text = self.setup_file().read_text(encoding="utf-8")
        self.assertIn('          python-version-file: "pyproject.toml"\n', text)

    def test_a_pyproject_without_requires_python_keeps_the_floor(self):
        (self.target / "pyproject.toml").write_text('[project]\nname = "x"\n', encoding="utf-8")
        self.configure()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertIn('          python-version: "3.11"\n',
                      self.setup_file().read_text(encoding="utf-8"))

    def test_the_uvx_runtime_installs_uv(self):
        self.configure()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude",
                                        "--runtime", "uvx", "--write")[0])
        self.assertIn("      - uses: astral-sh/setup-uv@v10\n",
                      self.setup_file().read_text(encoding="utf-8"))

    def test_without_the_projection_no_workflow_is_written(self):
        self.configure(projections=None)
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertFalse(self.setup_file().exists())

    def test_removing_the_key_removes_the_workflow(self):
        self.configure()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertTrue(self.setup_file().is_file())
        self.configure(projections=None)
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertFalse(self.setup_file().exists())

    def test_editing_the_workflow_is_drift_and_a_write_refuses(self):
        self.configure()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        path = self.setup_file()
        path.write_text(path.read_text(encoding="utf-8") + "\n# mine\n", encoding="utf-8")
        code, payload = self.deploy("--modules", "specs", "--harness", "claude", "--check")
        self.assertEqual(1, code)
        self.assertIn({"path": SETUP, "change": "edited"}, payload["changes"])
        code, payload = self.deploy("--modules", "specs", "--harness", "claude", "--write")
        self.assertEqual((2, "ct-deploy-edited"), (code, payload["code"]))
        self.assertIn(SETUP, payload["paths"])

    def test_a_command_with_a_quote_and_a_newline_stays_one_yaml_scalar(self):
        document = translate.copilot_setup_document(
            None, 'echo "a: b"\nuv sync', "vendor")
        self.assertIn('        run: "echo \\"a: b\\"\\nuv sync"\n', document)

    def test_the_tree_carries_the_workflow_only_with_the_projection(self):
        with tempfile.TemporaryDirectory() as tmp:
            target = pathlib.Path(tmp)
            plain = deploy_tree.build_tree(PLUGIN_ROOT, target, ["quenching-specs"], ["claude"])
            self.assertNotIn(SETUP, plain["tree"])
            projected = deploy_tree.build_tree(PLUGIN_ROOT, target, ["quenching-specs"],
                                               ["claude"], projections=["github"],
                                               worktree_setup="uv sync")
            self.assertIn(SETUP, projected["tree"])
            self.assertIn(b'run: "uv sync"', projected["tree"][SETUP][0])
