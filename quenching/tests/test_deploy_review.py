"""The code review's instruction seed: `REVIEW.md` at the root, opt-in by the `github` projection,
written only when the target carries the OKF standards index, and never owned by the manifest —
the review policy is the repository's, like `AGENTS.md`."""
from __future__ import annotations

import contextlib
import io
import json
import os
import pathlib
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

try:
    import _paths  # noqa: F401
except ModuleNotFoundError:
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    import _paths  # noqa: F401

from quenching.deploy import translate  # noqa: E402
from quenching.deploy import tree as deploy_tree  # noqa: E402
from quenching.deploy.cli import main as deploy_main  # noqa: E402

PLUGIN_ROOT = pathlib.Path(__file__).resolve().parent.parent


class Projection(unittest.TestCase):
    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.target = pathlib.Path(tmp.name)
        subprocess.run(["git", "-C", str(self.target), "init", "-q"], check=True,
                       capture_output=True)
        xdg = pathlib.Path(tempfile.mkdtemp(dir=tmp.name, prefix="xdg-"))
        env = mock.patch.dict(os.environ, {"XDG_CONFIG_HOME": str(xdg), "OPENCODE_CONFIG": ""})
        env.start()
        self.addCleanup(env.stop)
        precompile = mock.patch("quenching.deploy.cli._precompile", return_value=None)
        precompile.start()
        self.addCleanup(precompile.stop)

    def configure(self, projections=("github",)):
        document = {} if projections is None else {"shared": {"projections": list(projections)}}
        path = self.target / ".agents/quenching.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(document), encoding="utf-8")

    def bundle(self, standards=True):
        docs = self.target / "docs"
        docs.mkdir(parents=True, exist_ok=True)
        (docs / "index.md").write_text('---\nokf_version: "0.2"\n---\n\n# docs\n', encoding="utf-8")
        if standards:
            (docs / "standards").mkdir(parents=True, exist_ok=True)
            (docs / "standards/index.md").write_text("# standards\n", encoding="utf-8")

    def deploy(self, *argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(io.StringIO()):
            code = deploy_main(["--target", str(self.target), *argv, "--json"])
        return code, json.loads(out.getvalue() or "{}")

    def test_the_seed_points_at_the_standards_and_is_not_owned(self):
        self.configure()
        self.bundle()
        code, payload = self.deploy("--modules", "specs", "--harness", "claude", "--write")
        self.assertEqual(0, code, payload)
        review = (self.target / "REVIEW.md").read_text(encoding="utf-8")
        self.assertIn("# Review context", review)
        self.assertIn("`/docs/standards/index.md`", review)
        self.assertIn("`/docs/glossary.md`", review)
        self.assertIn("Seeded by `cq deploy`", review)
        self.assertNotIn("generated by cq deploy", review)
        files = json.loads((self.target / ".agents/.quenching-deploy.json").read_text())["files"]
        self.assertNotIn("REVIEW.md", files)

    def test_without_the_bundle_no_review_file_is_written(self):
        self.configure()
        code, payload = self.deploy("--modules", "specs", "--harness", "claude", "--write")
        self.assertEqual(0, code, payload)
        self.assertFalse((self.target / "REVIEW.md").exists())

    def test_without_the_standards_index_no_review_file_is_written(self):
        self.configure()
        self.bundle(standards=False)
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertFalse((self.target / "REVIEW.md").exists())

    def test_a_root_index_without_okf_version_is_not_a_bundle(self):
        self.configure()
        self.bundle()
        (self.target / "docs/index.md").write_text("# docs without frontmatter\n", encoding="utf-8")
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertFalse((self.target / "REVIEW.md").exists())

    def test_a_target_review_file_is_never_overwritten(self):
        self.configure()
        self.bundle()
        mine = self.target / "REVIEW.md"
        mine.write_text("# Our review rules\n", encoding="utf-8")
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertEqual("# Our review rules\n", mine.read_text(encoding="utf-8"))
        code, payload = self.deploy("--modules", "specs", "--harness", "claude", "--check")
        self.assertEqual(0, code, payload)
        self.assertEqual([], payload["changes"])

    def test_without_the_projection_no_review_file_is_written(self):
        self.configure(projections=None)
        self.bundle()
        self.assertEqual(0, self.deploy("--modules", "specs", "--harness", "claude", "--write")[0])
        self.assertFalse((self.target / "REVIEW.md").exists())

    def test_the_tree_carries_the_seed_only_with_the_projection_and_the_bundle(self):
        with tempfile.TemporaryDirectory() as tmp:
            target = pathlib.Path(tmp)
            self.assertNotIn("REVIEW.md", deploy_tree.build_tree(
                PLUGIN_ROOT, target, ["quenching-specs"], ["claude"], projections=["github"])["seeds"])
            (target / "docs/standards").mkdir(parents=True)
            (target / "docs/index.md").write_text('---\nokf_version: "0.2"\n---\n', encoding="utf-8")
            (target / "docs/standards/index.md").write_text("# standards\n", encoding="utf-8")
            built = deploy_tree.build_tree(PLUGIN_ROOT, target, ["quenching-specs"], ["claude"],
                                           projections=["github"])
            self.assertEqual(translate.REVIEW_SEED, built["seeds"]["REVIEW.md"])
