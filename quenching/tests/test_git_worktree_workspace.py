"""`cq git worktree workspace`: the machine-local projection of the slots into a `.code-workspace`.

The file is a client artifact of the same survey `slots` reports: the primary checkout and the
active slots by default, the whole pool with `--all`, and never a versioned file.
"""
from __future__ import annotations

import argparse
import contextlib
import io
import json
import os
import pathlib
import unittest

import _paths  # noqa: F401  — must precede the `quenching` import
from quenching.common.jsonc import jsonc_loads
from quenching.git import slots
from test_git_worktree_slots import SlotRepo, _git


def _workspace(**kw):
    base = dict(json=True, write=False, all=False, output=None)
    base.update(kw)
    return argparse.Namespace(**base)


class TheDocument(SlotRepo):
    def _run(self, **kw):
        buf = io.StringIO()
        with contextlib.redirect_stdout(buf), contextlib.redirect_stderr(io.StringIO()):
            code = slots.workspace(_workspace(**kw))
        return code, json.loads(buf.getvalue())

    def _held(self, branch="plan/1-a"):
        _code, got = self.run_verb("acquire", branch=branch)
        return got["path"]

    def test_the_default_projection_is_the_primary_and_the_active_slots(self):
        held = self._held()
        _code, got = self.run_verb("acquire", branch="plan/2-b")
        self.run_verb("release", path=got["path"])
        code, out = self._run()
        self.assertEqual(code, 0, out)
        paths = [folder["path"] for folder in out["folders"]]
        self.assertEqual(paths, [os.path.realpath(self.main), os.path.realpath(held)])
        self.assertEqual(out["folders"][0]["name"], "quenching")
        self.assertIn("slot 1", out["folders"][1]["name"])
        self.assertFalse(out["written"])
        self.assertFalse(os.path.exists(out["path"]))

    def test_all_adds_the_free_slots_and_the_other_worktrees(self):
        held = self._held()
        _code, free = self.run_verb("acquire", branch="plan/2-b")
        self.run_verb("release", path=free["path"])
        other = os.path.join(self.base, "repo-legacy")
        _git(self.main, "worktree", "add", "-q", "-b", "legacy", other)
        code, out = self._run(all=True)
        self.assertEqual(code, 0, out)
        paths = [folder["path"] for folder in out["folders"]]
        for expected in (os.path.realpath(self.main), os.path.realpath(held),
                         os.path.realpath(free["path"]), os.path.realpath(other)):
            self.assertIn(expected, paths)

    def test_write_creates_the_machine_local_file_and_prints_the_command(self):
        self._held()
        code, out = self._run(write=True)
        self.assertEqual(code, 0, out)
        self.assertTrue(out["written"])
        path = pathlib.Path(out["path"])
        self.assertEqual(path, pathlib.Path(self.main, ".vscode",
                                            "quenching-slots.code-workspace"))
        document = jsonc_loads(path.read_text(encoding="utf-8"))
        self.assertEqual(document["folders"], out["folders"])
        self.assertIn("code -n", out["command"])
        self.assertIn(str(path), out["command"])

    def test_the_projection_is_jsonc_with_its_own_header(self):
        _code, out = self._run()
        document = jsonc_loads(out["document"])
        self.assertEqual(list(document), ["folders"])
        self.assertTrue(out["document"].startswith("// Generated by `cq git worktree workspace`"))

    def test_an_explicit_output_path_wins(self):
        target = os.path.join(self.base, "custom.code-workspace")
        code, out = self._run(write=True, output=target)
        self.assertEqual(code, 0, out)
        self.assertEqual(out["path"], target)
        self.assertTrue(os.path.isfile(target))
