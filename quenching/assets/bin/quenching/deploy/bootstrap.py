"""The per-user bootstrap the deploy generates in `.quenching/bootstrap/`.

The deploy only WRITES these files; it never runs them. They are the user's to run by hand
(`--check` is read-only, `--write` is explicit), and they set up what lives outside the repository:
the `cq` launcher, the global OpenCode config, the Claude Code plugins and the VS Code user
settings. They are not in the manifest's `files`: `.quenching/` is not versioned, so a clone the CI
checks out would read their absence as drift. The manifest's `bootstrap` list names them instead.
"""
from __future__ import annotations

import json
from pathlib import Path

DIR = ".quenching/bootstrap"
SCRIPT = f"{DIR}/bootstrap.py"
SH = f"{DIR}/bootstrap.sh"
CMD = f"{DIR}/bootstrap.cmd"
FILES = (SCRIPT, SH, CMD)
TEMPLATE = "assets/bootstrap/bootstrap.py"
PLACEHOLDER = "__CONFIG__"

_SH = """#!/bin/sh
# Generated by `cq deploy`; run it by hand. Finds Python and runs bootstrap.py with the same
# arguments: --check (default, read-only) or --write.
here=$(cd "$(dirname "$0")" && pwd)
for py in python3 python; do
  if command -v "$py" >/dev/null 2>&1; then exec "$py" "$here/bootstrap.py" "$@"; fi
done
echo "bootstrap: Python 3 was not found on PATH" >&2
exit 2
"""

_CMD = (
    "@echo off\r\n"
    "rem Generated by `cq deploy`; run it by hand. Finds Python and runs bootstrap.py with the\r\n"
    "rem same arguments: --check (default, read-only) or --write.\r\n"
    "where py >nul 2>nul\r\n"
    "if %ERRORLEVEL% EQU 0 (\r\n"
    '  py -3 "%~dp0bootstrap.py" %*\r\n'
    ") else (\r\n"
    '  python "%~dp0bootstrap.py" %*\r\n'
    ")\r\n"
    "exit /b %ERRORLEVEL%\r\n"
)


def files(source: Path, version: str, harnesses: list[str],
          vscode: bool) -> dict[str, tuple[bytes, int]]:
    """The three generated files, `{rel: (bytes, mode)}`, from the template under `source`.

    Only the `CONFIG` block varies: the version, the declared harnesses and whether the repository
    declares VS Code. All three come from the repository's own layer and manifest, so every clone
    renders the same bytes."""
    template = (source / TEMPLATE).read_text(encoding="utf-8").replace("\r\n", "\n")
    if PLACEHOLDER not in template:
        raise ValueError(f"{TEMPLATE} carries no {PLACEHOLDER} block")
    config = json.dumps({"version": version, "harnesses": sorted(harnesses), "vscode": bool(vscode)},
                        sort_keys=True)
    return {SCRIPT: (template.replace(PLACEHOLDER, config).encode("utf-8"), 0o755),
            SH: (_SH.encode("utf-8"), 0o755),
            CMD: (_CMD.encode("utf-8"), 0o644)}
