"""Target translation for `cq deploy`.

The source is written in the target dialect.  This module rewrites only frontmatter, the
generated header, the grants (and OpenCode permissions) and the ``cq.cmd`` launcher note, and
refuses a source that still carries a plugin-surface id.  It never decides what to deploy; `tree`
does.  An agent has three projections of the one source — Claude, OpenCode and the Copilot file
under `.github/agents/` — and each reads the same role, grant and model band.
"""
from __future__ import annotations

import json
import re

from quenching.common.version import VERSION

PAYLOAD = ".agents/quenching"
CQ = PAYLOAD + "/bin/cq"
HEADER = f"<!-- generated by cq deploy {VERSION}; edit the source, not this file -->"
DROP_FRONTMATTER = {"model", "effort", "context", "hooks", "tools", "name"}
KEEP_FRONTMATTER = {"description", "argument-hint", "allowed-tools", "disable-model-invocation",
                    "user-invocable"}
AGENTS = ("spec-orchestrator", "spec-reviewer", "spec-runner", "spec-scout", "spec-verifier")

# A source id written for the plugin surface (`/quenching-specs:create`) is refused, not rewritten.
PLUGIN_ID = re.compile(r"(?<![\w-])/?quenching-[a-z]+:[A-Za-z0-9-]")
# Both the source grant and its already-translated form: a target-local `cq deploy` reads the
# payload's own agent bodies, so the second translation must produce the first one's output.
CQ_GRANT = re.compile(r"Bash\(((?:cq|" + re.escape(CQ) + r")(?:\.cmd)?)(?: ([^:()]+))?:\*\)$")


def agent_name(name: str) -> str:
    return "quenching-" + name


def _flat_description(lines: list[str], start: int) -> tuple[str, int]:
    """Read a folded/literal YAML scalar beginning at `start`; return its text and next index."""
    pieces: list[str] = []
    index = start
    while index < len(lines) and (lines[index].startswith((" ", "\t")) or not lines[index].strip()):
        pieces.append(lines[index].strip())
        index += 1
    return " ".join(piece for piece in pieces if piece), index


def split_frontmatter(raw: str) -> tuple[dict[str, str], str]:
    if not raw.startswith("---\n"):
        return {}, raw
    end = raw.find("\n---\n", 4)
    if end < 0:
        return {}, raw
    fields: dict[str, str] = {}
    lines = raw[4:end].splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        if not line.strip() or line.lstrip().startswith("#"):
            index += 1
            continue
        key, sep, value = line.partition(":")
        if not sep:
            index += 1
            continue
        key, value = key.strip(), value.strip()
        if value in {">", ">-", "|", "|-"}:
            value, index = _flat_description(lines, index + 1)
        else:
            index += 1
        fields[key] = value
    return fields, raw[end + len("\n---\n"):]


def scalar_value(value: str) -> str:
    """A frontmatter scalar as text, accepting a target's already JSON-quoted form."""
    if len(value) >= 2 and value.startswith('"') and value.endswith('"'):
        try:
            parsed = json.loads(value)
        except ValueError:
            return value
        return parsed if isinstance(parsed, str) else value
    return value


def transform_platform(text: str) -> str:
    """The source is already written in the target dialect: refuse what still needs rewriting."""
    if "CLAUDE_PLUGIN_ROOT" in text:
        raise ValueError("source still carries the plugin-root marker: CLAUDE_PLUGIN_ROOT")
    found = PLUGIN_ID.search(text)
    if found:
        raise ValueError(f"source still carries a plugin-surface id: {found.group(0)}")
    return text


MCP_SERVER = "quenching"


def _grant_names(tools: str) -> list[str]:
    return [item.strip() for item in re.split(r",\s*(?![^()]*\))", tools) if item.strip()]


def mcp_tools(names: list[str], mount: frozenset[str] | None = None) -> list[str] | None:
    """The `quenching` MCP tools a grant list covers: `None` for the whole server (`Bash`, or an
    unscoped `Bash(cq:*)`), else every tool under each scoped `Bash(cq <verbs>:*)` prefix — never
    wider than the shell grant it mirrors. `mount` keeps only the tools of the pillars the declared
    mount publishes: a name the server does not publish is not a grant."""
    from quenching.mcp import catalog
    if "Bash" in names:
        return None
    granted: list[str] = []
    for name in names:
        match = CQ_GRANT.match(name)
        if not match:
            continue
        if not match.group(2):
            return None
        granted.extend(tool for tool in catalog.tool_names(tuple(match.group(2).split()))
                       if (mount is None or catalog.pillar_of(tool) in mount)
                       and tool not in granted)
    return granted


def _with_mcp(value: str, enumerate_all: bool, mount: frozenset[str] | None = None) -> str:
    """Append the Claude Code names of the MCP tools the grant covers, once: `mcp__quenching` for
    the whole server where a rule may name it (skills), every tool by name where only a list of
    names is read (a subagent's `tools:`)."""
    from quenching.mcp import catalog
    names = _grant_names(value)
    tools = mcp_tools(names, mount)
    prefix = f"mcp__{MCP_SERVER}"
    if tools is None:
        wanted = ([f"{prefix}__{tool}" for tool in catalog.tool_names()
                   if mount is None or catalog.pillar_of(tool) in mount] if enumerate_all
                  else [prefix])
    else:
        wanted = [f"{prefix}__{tool}" for tool in tools]
    missing = [name for name in wanted if name not in names]
    return ", ".join([value, *missing]) if missing else value


def narrowed(names: list[str], mount: frozenset[str] | None = None) -> list[str]:
    """Each `Bash(cq <prefix>:*)` replaced by the shell grants its verbs with no MCP tool still
    need (`coverage.cli_residue`), on the same launcher; every other grant, and a prefix that
    names no verb, kept as is. Never wider than the source: the residue sits under its prefix.
    A `mount` keeps the shell grant of a pillar the mount hides, so no door closes."""
    from quenching.mcp import coverage
    out: list[str] = []
    for name in names:
        match = CQ_GRANT.match(name)
        residue = (coverage.cli_residue(tuple((match.group(2) or "").split()), mount)
                   if match else None)
        grants = [name] if residue is None else [
            f"Bash({match.group(1)} {' '.join(path)}:*)" for path in residue]
        out.extend(grant for grant in grants if grant not in out)
    return out


def transform_tools(value: str, enumerate_mcp: bool = False, narrow: bool = False,
                    mount: frozenset[str] | None = None) -> str:
    """Keep the shipped grant, re-rooted at the target-local `cq` and its `cq.cmd` twin, plus the
    `quenching` MCP tools that grant covers. `narrow` (the server registered, no CLI fallback)
    drops the shell grant each MCP tool replaces, keeping only `narrowed`'s residue; `mount` keeps
    the named tools inside the pillars the mount publishes."""
    value = _with_mcp(value, enumerate_mcp, mount)
    if narrow:
        value = ", ".join(narrowed(_grant_names(value), mount))
    value = re.sub(r"Bash\(cq((?:\.cmd)?[^)]*):\*\)",
                   lambda m: f"Bash({CQ}{m.group(1)}:*)", value)
    def target_agent(item: str) -> str:
        name = item.strip().split(":")[-1]
        return name if name.startswith("quenching-") else agent_name(name)

    value = re.sub(r"Agent\(([^)]*)\)",
                   lambda m: "Agent(" + ", ".join(
                       target_agent(item) for item in m.group(1).split(",")
                       if item.strip()) + ")", value)
    return value


def _frontmatter(fields: list[tuple[str, str]]) -> str:
    return "---\n" + "".join(f"{key}: {value}\n" for key, value in fields) + "---\n\n"


def _body(value: str) -> str:
    """A body with deployment's own separator/header removed, so a second pass is stable."""
    value = value.lstrip("\n")
    if value.startswith(HEADER):
        value = value[len(HEADER):].lstrip("\n")
    return value


LAUNCHER_NOTE = ("**Launcher.** On POSIX the skill calls `cq`; on Windows it calls "
                 "`cq.cmd`, the sibling the deploy installs beside `bin/cq`.\n\n")


def _with_launcher_note(body: str) -> str:
    """Put the platform choice right under the skill's title, once, where every run reads it."""
    if LAUNCHER_NOTE in body:
        return body
    head, _, tail = body.partition("\n")
    if head.startswith("# "):
        return f"{head}\n\n{LAUNCHER_NOTE}{tail.lstrip(chr(10))}"
    return LAUNCHER_NOTE + body


def skill_document(raw: str, name: str, narrow: bool = False,
                   mount: frozenset[str] | None = None) -> str:
    fields, body = split_frontmatter(raw)
    description = scalar_value(fields.get("description", ""))
    if not description:
        raise ValueError(f"skill has no description: {name}")
    out: list[tuple[str, str]] = [("name", name),
                                  ("description", json.dumps(transform_platform(description),
                                                             ensure_ascii=False))]
    for key in ("argument-hint", "allowed-tools", "disable-model-invocation", "user-invocable"):
        if key in fields:
            value = (transform_tools(fields[key], narrow=narrow, mount=mount)
                     if key == "allowed-tools"
                     else scalar_value(fields[key]))
            out.append((key, json.dumps(transform_platform(value), ensure_ascii=False)
                        if key == "argument-hint" else transform_platform(value)))
    return (_frontmatter(out) + HEADER + "\n\n"
            + _with_launcher_note(transform_platform(_body(body))))


def reference_document(raw: str) -> str:
    return transform_platform(raw)


def _cq_patterns(names: list[str]) -> list[str]:
    """One `<target cq> <verbs> *` pattern per scoped `Bash(cq <verbs>:*)` grant, in order."""
    patterns: list[str] = []
    for name in names:
        match = CQ_GRANT.match(name)
        if not match:
            continue
        launcher = CQ + (".cmd" if match.group(1).endswith(".cmd") else "")
        patterns.append(f"{launcher} {match.group(2)} *" if match.group(2) else f"{launcher} *")
    return patterns


SHELL_GRANT = re.compile(r"Bash\(([^():]+):\*\)$")


def _shell_patterns(names: list[str]) -> list[str]:
    """One `<command> *` pattern per scoped non-cq `Bash(<command>:*)` grant, in source order."""
    patterns: list[str] = []
    for name in names:
        match = SHELL_GRANT.match(name)
        if not match or CQ_GRANT.match(name):
            continue
        pattern = f"{match.group(1).strip()} *"
        if pattern not in patterns:
            patterns.append(pattern)
    return patterns


def opencode_permissions(tools: str | None, narrow: bool = False,
                         mount: frozenset[str] | None = None) -> dict[str, str | dict[str, str]]:
    """A source `tools:` list as OpenCode permissions: deny-first, with the cq grants allowed —
    under `narrow`, only the cq grants no MCP tool replaces (`narrowed`).

    OpenCode applies the last matching rule, so the catch-all bash pattern comes first. The
    mapping mirrors the OpenCode distribution's agent writer; it lives here too because the
    deploy payload must translate without the repository's scripts/ tree.
    """
    if tools is None:
        return {}
    source = _grant_names(tools)
    names = narrowed(source, mount) if narrow else source
    heads = {name.split("(", 1)[0] for name in names}
    granted: dict[str, str | dict[str, str]] = {}
    granted["edit"] = "allow" if heads & {"Edit", "Write", "NotebookEdit"} else "deny"
    granted["webfetch"] = "allow" if "WebFetch" in heads else "deny"
    if "Bash" in names:
        granted["bash"] = "allow"
    elif patterns := _cq_patterns(names) + _shell_patterns(names):
        granted["bash"] = {"*": "ask", **dict.fromkeys(patterns, "allow")}
    else:
        granted["bash"] = "ask" if "Bash" in heads else "deny"
    # Last match wins: the server-wide deny first, then the tools the cq grants cover.
    mcp = mcp_tools(source, mount)
    granted[f"{MCP_SERVER}_*"] = "allow" if mcp is None else "deny"
    granted.update(dict.fromkeys((f"{MCP_SERVER}_{tool}" for tool in mcp or []), "allow"))
    granted["task"] = _task_grant(names)
    return granted


def _task_grant(names: list[str]) -> str | dict[str, str]:
    """`Agent(a, b)`/`Task(a, b)` as a deny-first map by agent name, never wider than the source."""
    allowed: list[str] = []
    for name in names:
        head, _, rest = name.partition("(")
        if head not in {"Agent", "Task"}:
            continue
        if not rest:
            return "allow"
        allowed.extend(item.strip() for item in rest.rstrip(")").split(",") if item.strip())
    if not allowed:
        return "deny"
    return {"*": "deny", **dict.fromkeys(allowed, "allow")}


def opencode_agent_document(raw: str, name: str, narrow: bool = False,
                            mount: frozenset[str] | None = None) -> str:
    """An OpenCode subagent: `mode: subagent`, deny-first permissions and the translated body."""
    fields, body = split_frontmatter(raw)
    description = scalar_value(fields.get("description", ""))
    if not description:
        raise ValueError(f"agent has no description: {name}")
    granted = opencode_permissions(fields.get("tools"), narrow, mount)
    task = granted.pop("task", "allow")
    denies_task = task == "deny"
    if isinstance(task, dict):
        granted["task"] = task
    out = ["---", f"description: {json.dumps(transform_platform(description), ensure_ascii=False)}",
           "mode: subagent"]
    if granted:
        out.append("permission:")
        for key, value in granted.items():
            if isinstance(value, dict):
                out.append(f"  {key}:")
                out.extend(f'    "{pattern}": {mode}' for pattern, mode in value.items())
            else:
                out.append(f'  "{key}": {value}' if "*" in key else f"  {key}: {value}")
    if denies_task:
        out.extend(["tools:", "  task: false"])
    out.append("---")
    preferences = []
    if fields.get("model"):
        preferences.append(f"Source model tier: `{scalar_value(fields['model'])}`.")
    if fields.get("effort"):
        preferences.append(f"Declared effort: `{scalar_value(fields['effort'])}`.")
    preamble = "\n\n".join(preferences) + "\n\n" if preferences else ""
    return "\n".join(out) + "\n\n" + HEADER + "\n\n" + preamble + transform_platform(_body(body))


# A plugin agent is judgment work: `opus` and `sonnet` are the band, strongest first, and the small
# tier never enters it (`haiku` is refused below). One line per client change, dated like the
# bench's THRESHOLDS — the model inventory belongs to the client, not to this repository.
COPILOT_MODEL_BANDS = {
    "opus": ("Claude Opus 4.6", "Claude Sonnet 4.6"),
    "sonnet": ("Claude Sonnet 4.6", "Claude Opus 4.6"),
}
# The documented Copilot tool aliases (VS Code custom agent reference, 2026-11-25). `Skill` has no
# alias: the harness discovers skills itself, so the item is dropped rather than widened to `*`.
COPILOT_TOOLS = {"Read": "read", "Grep": "search", "Glob": "search", "Edit": "edit",
                 "Write": "edit", "NotebookEdit": "edit", "WebFetch": "web", "WebSearch": "web",
                 "TodoWrite": "todo", "Agent": "agent", "Task": "agent"}
COPILOT_DROPPED = {"Skill"}


def copilot_tools(value: str, narrow: bool = False, mount: frozenset[str] | None = None) -> list[str]:
    """The source grant as Copilot tool names, never wider than the Claude grant it mirrors.

    The already-translated grant is the input: `mcp__quenching__<tool>` becomes
    `quenching/<tool>` and the server-wide `mcp__quenching` becomes `quenching/*`, so the mount and
    the narrowing decide the list. A head with no alias refuses, because a silent drop loses a
    capability the source still declares."""
    names = _grant_names(transform_tools(value, enumerate_mcp=True, narrow=narrow, mount=mount))
    out: list[str] = []
    for name in names:
        head = name.split("(", 1)[0]
        if head == "mcp__quenching" and name == head:
            mapped = f"{MCP_SERVER}/*"
        elif name.startswith(f"mcp__{MCP_SERVER}__"):
            mapped = f"{MCP_SERVER}/{name.split('__', 2)[2]}"
        elif head == "Bash":
            mapped = "execute"
        elif head in COPILOT_DROPPED:
            continue
        elif head in COPILOT_TOOLS:
            mapped = COPILOT_TOOLS[head]
        else:
            raise ValueError(f"agent tool has no Copilot projection: {name}")
        if mapped not in out:
            out.append(mapped)
    return out


def copilot_models(value: str, name: str) -> str | None:
    """A source model band as the Copilot ordered list; the small tier is refused, never mapped."""
    band = scalar_value(value)
    if not band or band == "inherit":
        return None
    if band == "haiku":
        raise ValueError(f"agent {name} declares the small tier, which a plugin agent never uses")
    if band not in COPILOT_MODEL_BANDS:
        raise ValueError(f"agent {name} declares an unknown model band: {band}")
    return json.dumps(list(COPILOT_MODEL_BANDS[band]), ensure_ascii=False)


def _flow_list(items: list[str]) -> str:
    """A YAML flow sequence of plain scalars; every Copilot tool name is safe unquoted."""
    return "[" + ", ".join(items) + "]"


def copilot_agent_document(raw: str, name: str, narrow: bool = False,
                           mount: frozenset[str] | None = None) -> str:
    """The same agent in the Copilot custom-agent format (`.github/agents/<name>.agent.md`)."""
    fields, body = split_frontmatter(raw)
    description = scalar_value(fields.get("description", ""))
    if not description:
        raise ValueError(f"agent has no description: {name}")
    out: list[tuple[str, str]] = [("name", agent_name(name)),
                                  ("description", json.dumps(transform_platform(description),
                                                             ensure_ascii=False))]
    tools = copilot_tools(fields.get("tools", ""), narrow, mount)
    if tools:
        out.append(("tools", _flow_list(tools)))
    if fields.get("model"):
        models = copilot_models(fields["model"], name)
        if models:
            out.append(("model", models))
    if fields.get("effort"):
        out.append(("reasoning-effort", scalar_value(fields["effort"])))
    out.extend([("include-custom-instructions", "true"), ("target", "github-copilot")])
    return _frontmatter(out) + HEADER + "\n\n" + transform_platform(_body(body))


def agent_document(raw: str, name: str, narrow: bool = False,
                   mount: frozenset[str] | None = None) -> str:
    fields, body = split_frontmatter(raw)
    description = scalar_value(fields.get("description", ""))
    if not description:
        raise ValueError(f"agent has no description: {name}")
    out: list[tuple[str, str]] = [("name", agent_name(name)),
                                  ("description", json.dumps(transform_platform(description),
                                                             ensure_ascii=False))]
    if fields.get("tools"):
        out.append(("tools", transform_tools(fields["tools"], enumerate_mcp=True, narrow=narrow,
                                             mount=mount)))
    for key in ("model", "effort"):
        if fields.get(key):
            out.append((key, fields[key]))
    return _frontmatter(out) + HEADER + "\n\n" + transform_platform(_body(body))
