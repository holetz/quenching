"""PreToolUse(Bash|PowerShell) block-level guard: a commit or PR message never carries an AI coding
agent's co-authorship (a `Co-Authored-By:` trailer naming Claude/Anthropic, Copilot, Codex/OpenAI or
OpenCode, the `noreply@anthropic.com`/`noreply@openai.com` addresses, or a `Generated with`/`Generated
by` line naming an agent). The name is historical: the deploy entry, the module declaration and the
opt-out stay stable while the identity list is one constant.

Denies with the reason, so the agent reruns the command without it; it never rewrites the command,
since `updatedInput` only applies paired with `allow`, which would auto-approve whatever the command
chains. Opt out with QUENCHING_ALLOW_AGENT_COAUTHOR=1; the historical
QUENCHING_ALLOW_CLAUDE_COAUTHOR=1 stays accepted. Fails open: unparseable input or any crash prints
`{}`. Runs under Claude Code and the GitHub Copilot harness, from bash, PowerShell or cmd — the
deploy launches it through one polyglot `python -c` line.
"""
import json
import os
import re
import sys

AGENTS = "claude|anthropic|copilot|openai|codex|opencode"
FAST = re.compile(r"co-authored-by|generated (?:with|by)|noreply@(?:anthropic|openai)", re.I)
WRITES_MESSAGE = re.compile(r"\bgit\b[^\n|;&]*\b(commit|merge|tag|notes)\b|\bgh\s+pr\b|\bcq\s+git\b")
ATTRIBUTION = re.compile(rf"co-authored-by:[^\n]*(?:{AGENTS})|noreply@(?:anthropic|openai)\.com"
                         rf"|generated (?:with|by) \[?(?:{AGENTS})", re.I)
REASON = ("quenching removes agent co-authorship: drop every `Co-Authored-By:` trailer naming an AI "
          "coding agent and any `Generated with`/`Generated by` line from the message, then run the "
          "command again. Set `\"attribution\": {\"commit\": \"\", \"pr\": \"\"}` in settings to stop "
          "adding them.")


def command_of(event: dict) -> str | None:
    """The shell command, from Claude's `tool_input` or Copilot's `toolArgs` (an object or JSON text)."""
    args = event.get("tool_input")
    if args is None:
        args = event.get("toolArgs")
        if isinstance(args, str):
            args = json.loads(args)
    command = args.get("command") if isinstance(args, dict) else None
    return command if isinstance(command, str) else None


def decide(raw: str) -> dict:
    if (os.environ.get("QUENCHING_ALLOW_AGENT_COAUTHOR") == "1"
            or os.environ.get("QUENCHING_ALLOW_CLAUDE_COAUTHOR") == "1"
            or not FAST.search(raw)):
        return {}
    command = command_of(json.loads(raw))
    if not (command and WRITES_MESSAGE.search(command) and ATTRIBUTION.search(command)):
        return {}
    return {"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "deny",
                                   "permissionDecisionReason": REASON}}


def main() -> None:
    try:
        out = decide(sys.stdin.read())
    except Exception:
        out = {}
    print(json.dumps(out))


if __name__ == "__main__":
    main()
